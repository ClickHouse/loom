#!/usr/bin/env python3
"""loom init — onboarding CLI.

Goal: a new team is wired up — service account minted, .env written,
runnable starter script dropped, optional Langfuse project provisioned —
in under 10 minutes.

Usage:
    python dev/loom_init.py --namespace eng-tooling --agent agent-detector

What it does:
    1. Mints an HS256 service-account JWT scoped to (org, namespace, agent)
       with VIEWER+WRITER+ADMIN roles.
    2. Writes .env (or $LOOM_OUTPUT_DIR/.env) with LOOM_BASE_URL,
       LOOM_API_KEY, LOOM_ORG, LOOM_NAMESPACE, LOOM_AGENT.
    3. Drops `loom_starter.py` — a runnable script that does a memory
       set/get round-trip and a knowledge add/search round-trip.
    4. Optional: if --langfuse-host is given and LANGFUSE_ORG_API_KEY is
       set, POSTs to /api/public/projects to create a Langfuse project
       named {org}-{namespace}.

Refuses to clobber an existing .env unless --force.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path
from textwrap import dedent
from typing import Any

# Import path setup so the script runs from a checkout without install.
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "sdk" / "python"))

from server.auth import keyring  # noqa: E402
from server.auth.jwt import mint_token  # noqa: E402
from server.cli.doctor import dev_jwt_secret_warning  # noqa: E402

STARTER_TEMPLATE = '''\
"""Loom starter — generated by `loom init`.

Run me:  python loom_starter.py

Exercises the full hot path:
  - memory.set + memory.get  (proves auth + ClickHouse round-trip)
  - knowledge.add + knowledge.search  (proves embedder + ANN search)

It deletes the memory and the document it wrote before it exits.
"""

from __future__ import annotations

import asyncio
import os
import sys
import uuid

from loom import Agent


async def main() -> int:
    org = os.environ["LOOM_ORG"]
    namespace = os.environ["LOOM_NAMESPACE"]
    agent_name = os.environ["LOOM_AGENT"]
    base_url = os.environ.get("LOOM_BASE_URL", "http://localhost:7777")

    async with Agent(
        org=org,
        namespace=namespace,
        agent=agent_name,
        base_url=base_url,
    ) as agent:
        key = f"starter-{uuid.uuid4().hex[:8]}"
        doc_uri = f"loom-starter://{uuid.uuid4().hex[:8]}"
        try:
            # 1. memory round-trip
            await agent.memory.set(key, {"hello": "loom"}, memory_type="semantic")
            entry = await agent.memory.get(key)
            if entry is None:
                print("✗ memory.get returned nothing for the key just written", file=sys.stderr)
                return 1
            print(f"✓ memory ok  ({key} → v{entry['version']})")

            # 2. knowledge round-trip, scoped to the document just added
            await agent.knowledge.add(
                content="Loom is a memory and knowledge data plane for AI agents",
                source_uri=doc_uri,
                title="loom-starter",
                tags=["starter"],
            )
            hits = await agent.knowledge.search(
                "knowledge data plane for AI agents", top_k=3, uri_prefix=[doc_uri]
            )
            if not hits:
                print("✗ knowledge.search found nothing in the new document", file=sys.stderr)
                return 1
            print(f"✓ knowledge ok  ({len(hits)} hit(s))")
        finally:
            # 3. cleanup: both rows this script wrote, whether or not a step failed
            await agent.memory.delete(key)
            await agent.knowledge.delete(doc_uri)
            print("✓ cleanup ok")

    print()
    print("Loom is wired up. Next:")
    print("  - View traces:   $LANGFUSE_HOST  (if configured)")
    print("  - Read the docs: docs/index.md")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
'''


def _write_env(
    path: Path,
    *,
    base_url: str,
    api_key: str,
    org: str,
    namespace: str,
    agent: str,
    langfuse: dict[str, str] | None = None,
) -> None:
    lines = [
        f"LOOM_BASE_URL={base_url}",
        f"LOOM_API_KEY={api_key}",
        f"LOOM_ORG={org}",
        f"LOOM_NAMESPACE={namespace}",
        f"LOOM_AGENT={agent}",
    ]
    if langfuse:
        for k, v in langfuse.items():
            lines.append(f"{k}={v}")
    # The file carries a bearer token: owner-only from the first byte, and
    # re-tightened when --force overwrites a file that was wider.
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write("\n".join(lines) + "\n")
    path.chmod(0o600)


def _provision_langfuse(
    host: str,
    org_api_key: str,
    project_name: str,
    timeout_s: float = 5.0,
) -> dict[str, str]:
    """Create a Langfuse project; return {LANGFUSE_HOST, LANGFUSE_PUBLIC_KEY, LANGFUSE_SECRET_KEY}.

    Uses Langfuse's organization-scoped /api/public/projects endpoint.
    Raises RuntimeError on failure — caller decides whether to abort.
    """
    url = f"{host.rstrip('/')}/api/public/projects"
    req = urllib.request.Request(
        url,
        data=json.dumps({"name": project_name}).encode(),
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {org_api_key}",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout_s) as resp:
            body = json.loads(resp.read())
    except urllib.error.HTTPError as e:
        raise RuntimeError(f"Langfuse project create failed ({e.code}): {e.read()!r}") from e
    except urllib.error.URLError as e:
        raise RuntimeError(f"Langfuse host unreachable: {e.reason}") from e

    return {
        "LANGFUSE_HOST": host,
        "LANGFUSE_PUBLIC_KEY": body.get("publicKey", ""),
        "LANGFUSE_SECRET_KEY": body.get("secretKey", ""),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Provision a Loom service account + starter for a new team."
    )
    parser.add_argument(
        "--org",
        default="dev",
        help="Org the service account belongs to (default: %(default)s, "
        "the org the quickstart signs up with)",
    )
    parser.add_argument("--namespace", required=True, help="e.g. eng-tooling")
    parser.add_argument("--agent", required=True, help="e.g. agent-detector")
    parser.add_argument(
        "--base-url",
        default=os.environ.get("LOOM_BASE_URL", "http://localhost:7777"),
        help="Loom Control Plane URL (default: $LOOM_BASE_URL or http://localhost:7777)",
    )
    parser.add_argument(
        "--output-dir",
        default=os.environ.get("LOOM_OUTPUT_DIR", "."),
        help="Where to write .env + loom_starter.py (default: cwd)",
    )
    parser.add_argument(
        "--ttl-days",
        type=int,
        default=None,
        help="Service-account token TTL in days. Omit for an indefinite "
        "token (the default). Invalidation in that case is via "
        "`loom revoke-token` or `loom signing-key retire`.",
    )
    parser.add_argument(
        "--roles",
        default="VIEWER,WRITER,ADMIN",
        help="Comma-separated roles for the service account",
    )
    parser.add_argument(
        "--langfuse-host",
        default=os.environ.get("LANGFUSE_HOST"),
        help="If set + LANGFUSE_ORG_API_KEY in env, auto-provisions a Langfuse project.",
    )
    parser.add_argument("--force", action="store_true", help="Overwrite existing .env")
    parser.add_argument(
        "--json",
        action="store_true",
        help="Emit one-line JSON summary on stdout (for scripting)",
    )
    args = parser.parse_args(argv)

    out_dir = Path(args.output_dir).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    env_path = out_dir / ".env"
    starter_path = out_dir / "loom_starter.py"

    if env_path.exists() and not args.force:
        print(
            f"✗ {env_path} already exists. Re-run with --force to overwrite.",
            file=sys.stderr,
        )
        return 2

    if warning := dev_jwt_secret_warning():
        print(f"! {warning}", file=sys.stderr)

    keyring.load_for_offline_mint()
    subject = f"sa-{args.namespace}-{args.agent}"
    api_key = mint_token(
        subject=subject,
        org=args.org,
        namespaces=[args.namespace],
        roles=[r.strip() for r in args.roles.split(",") if r.strip()],
        ttl_seconds=(args.ttl_days * 86400) if args.ttl_days else None,
        is_service_account=True,
    )

    langfuse_env: dict[str, str] = {}
    langfuse_status = "skipped (no --langfuse-host)"
    if args.langfuse_host:
        org_api_key = os.environ.get("LANGFUSE_ORG_API_KEY")
        if not org_api_key:
            langfuse_status = "skipped (LANGFUSE_ORG_API_KEY not set)"
        else:
            try:
                langfuse_env = _provision_langfuse(
                    host=args.langfuse_host,
                    org_api_key=org_api_key,
                    project_name=f"{args.org}-{args.namespace}",
                )
                langfuse_status = f"provisioned ({langfuse_env['LANGFUSE_HOST']})"
            except RuntimeError as e:
                langfuse_status = f"failed: {e}"

    _write_env(
        env_path,
        base_url=args.base_url,
        api_key=api_key,
        org=args.org,
        namespace=args.namespace,
        agent=args.agent,
        langfuse=langfuse_env or None,
    )
    starter_path.write_text(STARTER_TEMPLATE)
    starter_path.chmod(0o755)

    summary: dict[str, Any] = {
        "ok": True,
        "subject": subject,
        "org": args.org,
        "namespace": args.namespace,
        "agent": args.agent,
        "env_path": str(env_path),
        "starter_path": str(starter_path),
        "ttl_days": args.ttl_days,
        "langfuse": langfuse_status,
    }

    ttl_label = f"{args.ttl_days}d" if args.ttl_days else "indefinite"
    if args.json:
        print(json.dumps(summary))
    else:
        print(
            dedent(f"""\
            ✓ Service account minted: {subject}  (roles={args.roles}, ttl={ttl_label})
            ✓ Config written:         {env_path}
            ✓ Starter script:         {starter_path}
            ✓ Langfuse:               {langfuse_status}

            Next:
              cd {out_dir}
              set -a && source .env && set +a
              python loom_starter.py
            """)
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
