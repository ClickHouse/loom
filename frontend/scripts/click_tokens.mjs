// Writes src/click-tokens.css: the Click UI light-theme variables that src/styles.css reads,
// copied from the installed @clickhouse/click-ui, and nothing else — the full token sheet is
// 135 kB of CSS on every page for about forty values. Run after bumping the package:
//
//   node scripts/click_tokens.mjs
//
// `--check` exits 1 instead of writing when the file is out of date (the unit test runs it).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SHEET = path.join(root, "node_modules/@clickhouse/click-ui/dist/esm/theme/styles/tokens-light.css");
const STYLES = path.join(root, "src/styles.css");
const OUT = path.join(root, "src/click-tokens.css");

export function clickTokensCss() {
  const sheet = fs.readFileSync(SHEET, "utf8");
  const block = /\[data-cui-theme="light"\]\s*\{([^}]*)\}/.exec(sheet);
  if (!block) throw new Error(`no [data-cui-theme="light"] block in ${SHEET}`);
  const values = new Map();
  for (const m of block[1].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) values.set(m[1], m[2].trim());

  const wanted = new Set();
  const visit = (text) => {
    for (const [, name] of text.matchAll(/var\((--(?:global|click)-[\w-]+)/g)) {
      if (wanted.has(name)) continue;
      if (!values.has(name)) throw new Error(`src/styles.css reads ${name}, which Click UI does not define`);
      wanted.add(name);
      visit(values.get(name));
    }
  };
  visit(fs.readFileSync(STYLES, "utf8"));

  const version = JSON.parse(
    fs.readFileSync(path.join(root, "node_modules/@clickhouse/click-ui/package.json"), "utf8"),
  ).version;
  const lines = [...wanted].sort().map((name) => `  ${name}: ${values.get(name)};`);
  return `/* Generated by scripts/click_tokens.mjs from @clickhouse/click-ui ${version} (light theme). Do not edit. */\n:root {\n${lines.join("\n")}\n}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = clickTokensCss();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== css) {
      console.error("src/click-tokens.css is out of date: run node scripts/click_tokens.mjs");
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUT, css);
    console.log(`wrote ${path.relative(root, OUT)}`);
  }
}
