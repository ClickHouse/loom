def test_go_generated_header_before_the_package_clause() -> None:
    assert (
        is_generated(
            "a/x.pb.go",
            b"// Code generated by protoc-gen-go. DO NOT EDIT.\n// versions:\npackage pb\n",
        )
        == "header:go"
    )
    licensed = b"/*\nCopyright 2024.\n*/\n\n// Code generated by controller-gen. DO NOT EDIT.\n\npackage v1\n"
    assert is_generated("api/v1/zz_generated.deepcopy.go", licensed) == "header:go"
    # the convention: the comment counts only BEFORE the package clause
    assert is_generated("a/x.go", b"package main\n// Code generated by hand. DO NOT EDIT.\n") == ""
    assert (
        is_generated(
            "a/x.go", b"// Code generated? no: this file is generated by hand\npackage x\n"
        )
        == ""
    )
    assert is_generated("a/x.go", b"package x\n\nfunc F() {}\n") == ""


def test_generated_marker_in_the_first_lines_of_any_language() -> None:
    assert is_generated(
        "a/x.ts", b"/* eslint-disable */\n// @generated by graphql-codegen\nexport {};\n"
    ) == ("marker:@generated")
    assert is_generated("a/x.py", b"# @generated\nX = 1\n") == "marker:@generated"
    assert is_generated("a/x.ts", b"const a = 1;\n" * 10 + b"// @generated\n") == ""  # too far down
    assert is_generated("a/x.md", b"The word @generated in prose is not a marker\n") == ""


def test_gitattributes_linguist_patterns_become_ignore_globs() -> None:
    text = (
        "# fixtures\n"
        "op/util/spawn/testdata/**/*.json linguist-generated=true\n"
        "op/util/spawn/testdata/**/*.hash linguist-generated=true\n"
        "stress/.claude/rules/*.md linguist-generated\n"
        "third/** linguist-vendored\n"
        "docs/*.md linguist-documentation\n"
        "src/*.go -linguist-generated\n"
        "*.go text eol=lf\n"
    )
    pats = parse_gitattributes(text)
    assert pats == (
        "op/util/spawn/testdata/**/*.json",
        "op/util/spawn/testdata/**/*.hash",
        "stress/.claude/rules/*.md",
        "third/**",
    )
    d = Denylist(patterns=pats)
    assert d.reason("op/util/spawn/testdata/Flags/00451868.server.hash").startswith(
        "excluded: pattern"
    )
    assert d.reason("op/util/spawn/spawn.go") == ""
    assert d.reason("third/lib/x.c").startswith("excluded: pattern")


def test_refusal_orders_path_then_binary_then_generated_per_entry() -> None:
    gen = b"// Code generated by mockery v2. DO NOT EDIT.\npackage mocks\n"
    off = Denylist()
    assert off.refusal("m/mock_store.go", gen) == ""  # the entry did not ask
    assert off.refusal("m/blob.go", b"\x00\x01") == "excluded: binary"
    on = Denylist(exclude_generated=True, patterns=("vendor/",))
    assert on.refusal("m/mock_store.go", gen) == "excluded: generated (header:go)"
    assert on.refusal("vendor/m/mock_store.go", gen) == "excluded: pattern vendor/"
    assert on.refusal("m/store.go", b"package store\n") == ""


def test_repo_entry_carries_exclude_generated(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(
        settings,
        "code_repos_json",
        ('[{"namespace": "code-mono", "exclude_generated": true}, {"namespace": "code-other"}]'),
    )
    monkeypatch.setattr(settings, "code_ingest_exclude", "", raising=False)
    a, b = configured_repos()
    assert a.exclude_generated is True and b.exclude_generated is False
    gen = b"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage pb\n"
    assert denylist_for(a).refusal("api/x.pb.go", gen).startswith("excluded: generated")
    assert denylist_for(b).refusal("api/x.pb.go", gen) == ""
    assert (
        denylist_for(b, attributes_text="gen/** linguist-generated\n")
        .reason("gen/a.go")
        .startswith("excluded: pattern")
    )


@pytest.mark.asyncio
async def test_load_denylist_reads_the_gitattributes_beside_the_ignore_file() -> None:
    def Cfg(*_a: Any, **_k: Any) -> Any:
        return repo_config(
            git_dir="/nowhere",
            ignore_file=".loomignore",
            exclude=(),
            include_contrib=False,
            exclude_generated=True,
        )

    files = {".loomignore": b"*.snap\n", ".gitattributes": b"fixtures/** linguist-generated=true\n"}

    async def show_file(_git_dir: str, _sha: str, name: str, max_bytes: int = 0) -> bytes | None:
        return files.get(name)

    d = await load_denylist(Cfg(), "abc", show_file)
    assert d.reason("a/b.snap").startswith("excluded: pattern *.snap")
    assert d.reason("fixtures/x/y.json").startswith("excluded: pattern fixtures/**")
    assert d.exclude_generated is True


def test_infrastructure_extensions_chunk_as_config_and_rules_as_docs() -> None:
    assert detect_by_extension("x/policy.rego") == "config"
    assert detect_by_extension("grafana/dash.libsonnet") == "jsonnet"
    # Terraform and terragrunt have a lane of their own
    for p in ("infra/main.tf", "env/prod.tfvars", "live/terragrunt.hcl"):
        assert detect_by_extension(p) == "hcl", p
    assert detect_by_extension(".cursor/rules/go.mdc") == "doc"
    assert detect_by_extension("experiments/x/dashboard.html") == "doc"
    assert detect_by_extension("go.sum") == ""  # a checksum list is not indexed


