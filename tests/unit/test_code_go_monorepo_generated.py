MODS = {
    "go.mod": "module example.com/mono\n\ngo 1.22\n\nreplace (\n"
    "\tgo.yaml.in/yaml/v2 v2.4.3 => ./internal/patches/yaml\n)\n",
    "svc/go.mod": "module example.com/mono/svc\n\nrequire example.com/mono/lib v0.0.0\n\n"
    "replace example.com/mono/lib => ../lib\n",
    "lib/go.mod": "module example.com/mono/lib\n",
    "tools/airgap/go.mod": "module example.com/mono/airgap-tools\n"
    "replace example.com/outside => ../../../elsewhere\n",
}


def test_module_index_orders_longest_first_and_reads_relative_replaces() -> None:
    index = go_module_index(MODS)
    assert index[0][0] == "example.com/mono/airgap-tools"  # a module path unlike its directory
    assert ("example.com/mono/svc", "svc") in index and ("example.com/mono/lib", "lib") in index
    assert ("example.com/mono", "") in index
    # a relative replace maps the replaced path onto its directory; a replace
    # that climbs above the root names nothing
    assert ("go.yaml.in/yaml/v2", "internal/patches/yaml") in index
    assert not any(m == "example.com/outside" for m, _ in index)
    # a go.mod's own module line beats a replace onto the same path
    idx2 = go_module_index(
        {"a/go.mod": "module x/a\nreplace x/b => ../elsewhere\n", "b/go.mod": "module x/b\n"}
    )
    assert dict(idx2)["x/b"] == "b"


def test_module_for_picks_the_nearest_module_at_a_slash_boundary() -> None:
    index = go_module_index(MODS)
    assert go_modules(index)("example.com/mono/svc/internal/h") == (
        "example.com/mono/svc",
        "svc",
    )
    assert go_modules(index)("example.com/mono/lib/store") == ("example.com/mono/lib", "lib")
    assert go_modules(index)("example.com/mono/cmd") == ("example.com/mono", "")
    assert go_modules(index)("example.com/mono/svcx") == ("example.com/mono", "")  # not `svc/`
    assert go_modules(index)("example.com/mono/airgap-tools/x") == (
        "example.com/mono/airgap-tools",
        "tools/airgap",
    )
    assert go_modules(index)("fmt") == ("", "")
    assert go_modules(index)("github.com/jackc/pgx/v5") == ("", "")


def test_indexed_resolution_returns_hits_and_the_listing_rungs_input() -> None:
    index = go_module_index(MODS)
    specs = [
        "fmt",
        "example.com/mono/lib/store",
        "example.com/mono/svc/internal/handler",
        "example.com/mono/airgap-tools/cli",
    ]
    wanted = go_wanted_paths(specs, index)
    assert "lib/store/store.go" in wanted and "tools/airgap/cli/cli.go" in wanted
    assert not any(w.startswith("fmt") for w in wanted)
    present = {"lib/store/store.go", "svc/internal/handler/serve.go"}
    resolved, unresolved = go_resolve_imports_indexed(specs, index, present)
    assert resolved == ["lib/store/store.go"]
    # the two in-repository imports no conventional name satisfied, with the
    # package directory the listing rung reads; `fmt` is outside every module
    assert unresolved == [
        ("example.com/mono/svc/internal/handler", "svc/internal/handler"),
        ("example.com/mono/airgap-tools/cli", "tools/airgap/cli"),
    ]


def test_parse_keeps_raw_imports_for_the_resolver() -> None:
    pf = parse_go(
        "svc/main.go", b'package main\nimport (\n\t"fmt"\n\t"example.com/mono/lib/store"\n)\n'
    )
    assert go_imports(pf) == ["fmt", "example.com/mono/lib/store"]
    assert pf.includes == []


