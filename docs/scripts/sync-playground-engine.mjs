import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("../../server/code/domain/anchor_state.py", import.meta.url);
const target = new URL("../api/playground/_loom_anchor_state.py", import.meta.url);
const generated = `# Generated by docs/scripts/sync-playground-engine.mjs.\n${readFileSync(source, "utf8")}`;

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== generated) {
    throw new Error("Playground engine is out of date. Run node docs/scripts/sync-playground-engine.mjs.");
  }
} else {
  writeFileSync(target, generated);
}
