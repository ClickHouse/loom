"""Pure rules for `code.conventions`: the ClickHouse repository's recurring maintainer
checks as deterministic facts over a diff and what the index / mirror already hold. No
model, no opinion — each rule returns a verdict with the evidence rows (`path`, `line`,
`text`) that decide it and an epistemic label (`exact` when every read the rule needed
succeeded, `lower_bound` when a read was a floor or the rule is a prior).

Verdicts: `violated` | `satisfied` | `not_applicable` | `unknown`, plus
`unusual` for the two lead rules (`changelog_category`,
`wide_callers_untested`) whose "firing" is a prior, not a rule.

Everything here is text → dict. The handler owns the reads (index, ledger,
bare mirror) and hands their results in.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any

from server.code.domain.index import setting_facts as sf

VIOLATED = "violated"
SATISFIED = "satisfied"
NOT_APPLICABLE = "not_applicable"
UNKNOWN = "unknown"
UNUSUAL = "unusual"
VERDICTS = (VIOLATED, SATISFIED, NOT_APPLICABLE, UNKNOWN, UNUSUAL)

EXACT = "exact"
LOWER_BOUND = "lower_bound"

CHECK_RULES = (
    "setting_history",
    "setting_docs",
    "error_code_declared",
    "bugfix_has_test",
    "test_only_change",
    "stateless_test_number",
    "reference_missing",
)
LEAD_RULES = ("changelog_category", "wide_callers_untested")
RULES = (*CHECK_RULES, *LEAD_RULES)

DOCS_PREFIX = "docs/"
# Generated reference pages: the session, MergeTree, format and server
# settings pages are generated from the declarations
# (`{/*AUTOGENERATED_START*/}` … "autogenerated from source" in every page
# under this prefix), so a settings PR carries no docs change for them.
GENERATED_DOCS_PREFIX = "docs/reference/settings/"

# Which declaration files feed a change-history list (the stateless test
# 03999_stateless_settings_history compares `system.settings` and the
# MergeTree settings against the history; server settings have none).
HISTORY_TRACKED_FILES = frozenset(
    {
        "src/Core/Settings.cpp",
        "src/Storages/MergeTree/MergeTreeSettings.cpp",
        "src/Core/FormatFactorySettings.h",
    }
)


_DECLARE_RE = re.compile(
    r"DECLARE(?:_WITH_ALIAS)?\(\s*(?P<type>\w+)\s*,\s*(?P<name>\w+)\s*,\s*"
    r"(?P<default>" + r'"(?:[^"\\]|\\.)*"|[^,]+?' + r")\s*,"
)
_HISTORY_ENTRY_RE = re.compile(r'\{\s*"(?P<name>[A-Za-z_][A-Za-z0-9_]*)"\s*,')
_ERROR_CODE_USE_RE = re.compile(r"\bErrorCodes::(?P<name>[A-Z][A-Z0-9_]+)\b")
# check_cpp.sh's EXTERN_TYPES_EXCLUDES for ErrorCodes: the namespace's own
# API, not codes (all lower-case anyway; kept explicit).
_ERROR_CODE_EXEMPT = frozenset(
    {
        "ErrorCode",
        "getName",
        "increment",
        "end",
        "extendedMessage",
        "values",
        "getErrorCodeByName",
        "Value",
    }
)
_ERROR_CODE_FILE_RE = re.compile(r"^(src|programs|base|utils)/.*\.(cpp|h)$")
ERROR_CODES_REGISTRY = "src/Common/ErrorCodes.cpp"
_STATELESS_RE = re.compile(r"^tests/queries/0_stateless/(?P<num>\d{5})_(?P<rest>[^/]+)$")
_STATELESS_EXT_RE = re.compile(r"\.(reference\.j2|reference|sql\.j2|sql|sh|python|py|expect|j2)$")


# ---------------------------------------------------------------- the diff


@dataclass
class FileDiff:
    path: str
    status: str = "M"  # A | M | D
    # (new-side line, text) / (old-side line, text)
    added: list[tuple[int, str]] = field(default_factory=list)
    removed: list[tuple[int, str]] = field(default_factory=list)


@dataclass
class Diff:
    files: dict[str, FileDiff] = field(default_factory=dict)
    truncated: bool = False
    bytes: int = 0

    def added_in(self, path: str) -> list[tuple[int, str]]:
        f = self.files.get(path)
        return f.added if f else []


_HUNK_RE = re.compile(r"^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@")


def parse_unified_diff(text: str, *, truncated: bool = False) -> Diff:
    """`diff --git a/X b/Y` sections with their hunks; added lines carry the
    new-side line number, removed lines the old-side one. Tolerant: a
    malformed hunk contributes nothing, a file header without hunks is a
    status-only entry (a binary or a mode change)."""
    out = Diff(truncated=truncated, bytes=len(text or ""))
    cur: FileDiff | None = None
    new_ln = old_ln = 0
    in_hunk = False
    for raw in (text or "").splitlines():
        if raw.startswith("diff --git "):
            path = _path_of_header(raw)
            cur = out.files.setdefault(path, FileDiff(path=path))
            in_hunk = False
            continue
        if cur is None:
            continue
        if not in_hunk:
            if raw.startswith("new file mode"):
                cur.status = "A"
                continue
            if raw.startswith("deleted file mode"):
                cur.status = "D"
                continue
            if raw.startswith("+++ b/") and cur.path == "":
                cur.path = raw[6:]
                continue
        if raw.startswith("@@"):
            m = _HUNK_RE.match(raw)
            if not m:
                in_hunk = False
                continue
            old_ln, new_ln = int(m.group(1)), int(m.group(3))
            in_hunk = True
            continue
        if not in_hunk:
            continue
        if raw.startswith("+") and not raw.startswith("+++ "):
            cur.added.append((new_ln, raw[1:]))
            new_ln += 1
        elif raw.startswith("-") and not raw.startswith("--- "):
            cur.removed.append((old_ln, raw[1:]))
            old_ln += 1
        elif raw.startswith("\\"):
            continue  # "\ No newline at end of file"
        else:
            new_ln += 1
            old_ln += 1
    return out


def _path_of_header(line: str) -> str:
    # `diff --git a/p b/p` — take the b/ side; paths with spaces keep them
    body = line[len("diff --git ") :]
    i = body.find(" b/")
    if i < 0:
        return body.strip()
    return body[i + 3 :].strip()


def stem_of_stateless(path: str) -> tuple[str, str] | None:
    """(number, stem) for a stateless test file; None otherwise. The stem is
    the file name without its test extension chain (`04652_x.sql.j2` and
    `04652_x.reference.j2` share `04652_x`)."""
    m = _STATELESS_RE.match(path)
    if not m:
        return None
    name = m.group("num") + "_" + m.group("rest")
    return m.group("num"), _STATELESS_EXT_RE.sub("", name)


# ---------------------------------------------------------------- rule results


@dataclass
class RuleResult:
    rule: str
    verdict: str = UNKNOWN
    evidence: list[dict[str, Any]] = field(default_factory=list)
    epistemic: str = EXACT
    note: str = ""

    def as_dict(self) -> dict[str, Any]:
        out: dict[str, Any] = {
            "rule": self.rule,
            "verdict": self.verdict,
            "evidence": self.evidence[:40],
            "epistemic": self.epistemic,
        }
        if self.note:
            out["note"] = self.note
        return out


def ev(path: str, line: int, text: str, **extra: Any) -> dict[str, Any]:
    row: dict[str, Any] = {"path": path, "line": int(line or 0), "text": (text or "").strip()[:200]}
    row.update({k: v for k, v in extra.items() if v not in ("", None)})
    return row


# ---------------------------------------------------------------- settings (rules 1, 2)


@dataclass
class SettingChange:
    name: str
    file: str
    line: int
    text: str
    kind: str  # new | default_changed
    old_default: str = ""
    new_default: str = ""


def setting_changes(diff: Diff) -> list[SettingChange]:
    """DECLAREs the diff adds in the declaration files: a `new` setting (no
    removed DECLARE of the name) or a `default_changed` one (the removed
    line declared it with another default). A description- or flags-only
    edit is neither and needs no history entry (03999 compares defaults)."""
    out: list[SettingChange] = []
    for path in sf.DECLARATION_FILES:
        fd = diff.files.get(path)
        if fd is None:
            continue
        removed = {}
        for _ln, text in fd.removed:
            m = _DECLARE_RE.search(text)
            if m:
                removed[m.group("name")] = m.group("default").strip()
        seen: set[str] = set()
        for ln, text in fd.added:
            m = _DECLARE_RE.search(text)
            if not m:
                continue
            name = m.group("name")
            if name in seen:
                continue
            seen.add(name)
            new_default = m.group("default").strip()
            if name not in removed:
                out.append(SettingChange(name, path, ln, text, "new", "", new_default))
            elif removed[name] != new_default:
                out.append(
                    SettingChange(
                        name, path, ln, text, "default_changed", removed[name], new_default
                    )
                )
    return out


_LITERAL_RE = re.compile(r'^(?:-?\d[\d._]*[a-zA-Z]*|true|false|"(?:[^"\\]|\\.)*")$')


def _is_literal(default: str) -> bool:
    return bool(_LITERAL_RE.match((default or "").strip()))


def history_names_in_diff(diff: Diff) -> dict[str, tuple[int, str]]:
    """Setting names the diff adds to SettingsChangesHistory.cpp → (line, text)."""
    out: dict[str, tuple[int, str]] = {}
    for ln, text in diff.added_in(sf.HISTORY_FILE):
        for m in _HISTORY_ENTRY_RE.finditer(text):
            out.setdefault(m.group("name"), (ln, text))
    return out


def rule_setting_history(
    changes: list[SettingChange],
    diff: Diff,
    history_chunks: list[dict[str, Any]] | None,
) -> RuleResult:
    r = RuleResult("setting_history")
    tracked = [c for c in changes if c.file in HISTORY_TRACKED_FILES]
    if not changes:
        r.verdict, r.note = NOT_APPLICABLE, "no DECLARE added or changed in the declaration files"
        return r
    if not tracked:
        r.verdict = NOT_APPLICABLE
        r.note = (
            "server settings carry no change history "
            "(only Settings / MergeTreeSettings / format settings do)"
        )
        r.evidence = [ev(c.file, c.line, c.text, setting=c.name) for c in changes]
        return r
    in_diff = history_names_in_diff(diff)
    missing: list[SettingChange] = []
    for c in tracked:
        if c.name in in_diff:
            ln, text = in_diff[c.name]
            r.evidence.append(ev(sf.HISTORY_FILE, ln, text, setting=c.name, where="diff"))
            continue
        if history_chunks is None:
            r.epistemic = LOWER_BOUND
            missing.append(c)
            continue
        entries = sf.parse_history(history_chunks, c.name)
        if entries:
            e = entries[0]
            text = f'{{"{c.name}", {e.old}, {e.new}, "{e.reason}"}}'
            r.evidence.append(
                ev(sf.HISTORY_FILE, e.line, text, setting=c.name, where="index", release=e.version)
            )
        else:
            missing.append(c)
    if missing and history_chunks is None:
        r.verdict, r.note = UNKNOWN, "SettingsChangesHistory.cpp could not be read from the index"
        r.evidence = [ev(c.file, c.line, c.text, setting=c.name, kind=c.kind) for c in missing]
        return r
    if missing:
        r.verdict = VIOLATED
        r.evidence = [
            ev(
                c.file,
                c.line,
                c.text,
                setting=c.name,
                kind=c.kind,
                old_default=c.old_default,
                new_default=c.new_default,
            )
            for c in missing
        ] + r.evidence
        r.note = (
            f"{len(missing)} setting(s) added or re-defaulted without a "
            f'{{"name", old, new, "reason"}} entry in {sf.HISTORY_FILE} '
            "(the stateless test 03999_stateless_settings_history fails on this)"
        )
        if all(c.kind == "default_changed" and not _is_literal(c.new_default) for c in missing):
            # `1000000000` → `default_query_profiler_period_ns`: the text changed, the
            # value may not have — the history test compares values
            r.epistemic = LOWER_BOUND
            r.note += "; the new default is an expression, its value may equal the old one"
        return r
    r.verdict = SATISFIED
    return r


def rule_setting_docs(
    changes: list[SettingChange],
    diff: Diff,
    docs_mentions: dict[str, list[str] | None],
) -> RuleResult:
    """`docs_mentions[name]`: docs paths on the mirror's tip that mention the
    setting, None when that read failed. The reference pages under
    `docs/reference/settings/` are generated from the declarations, so a
    settings PR that leaves docs untouched is `not_applicable` for a name
    with no hand-written mention yet — never `violated` for a generated page."""
    r = RuleResult("setting_docs")
    if not changes:
        r.verdict, r.note = NOT_APPLICABLE, "no DECLARE added or changed"
        return r
    docs_added: dict[str, list[tuple[str, int, str]]] = {}
    for path, fd in diff.files.items():
        if not path.startswith(DOCS_PREFIX):
            continue
        for ln, text in fd.added:
            for c in changes:
                if c.name in text:
                    docs_added.setdefault(c.name, []).append((path, ln, text))
    unread = False
    skipped = 0
    generated_only: list[str] = []
    checked = 0
    for c in changes:
        if c.name in docs_added:
            p, ln, text = docs_added[c.name][0]
            r.evidence.append(ev(p, ln, text, setting=c.name, where="diff"))
            checked += 1
            continue
        if c.name not in docs_mentions:
            # past the per-call cap on mirror greps: not checked, said so
            skipped += 1
            r.evidence.append(ev(c.file, c.line, c.text, setting=c.name, where="not_checked"))
            continue
        paths = docs_mentions[c.name]
        checked += 1
        if paths is None:
            unread = True
            r.evidence.append(ev(c.file, c.line, c.text, setting=c.name, where="docs_unread"))
            continue
        hand = [p for p in paths if not p.startswith(GENERATED_DOCS_PREFIX)]
        gen = [p for p in paths if p.startswith(GENERATED_DOCS_PREFIX)]
        if hand or gen:
            r.evidence.append(
                ev(
                    (hand or gen)[0],
                    0,
                    "",
                    setting=c.name,
                    where="mirror",
                    generated=bool(gen and not hand),
                    mentions=len(paths),
                )
            )
        else:
            generated_only.append(c.name)
            r.evidence.append(
                ev(
                    c.file,
                    c.line,
                    c.text,
                    setting=c.name,
                    where="no_docs_mention",
                    generated_page=True,
                )
            )
    tail = f"; {skipped} of {len(changes)} name(s) not checked (per-call cap)" if skipped else ""
    if unread:
        r.verdict, r.note = UNKNOWN, "the docs tree could not be read from the mirror" + tail
        return r
    if not checked:
        r.verdict, r.note = UNKNOWN, "no name checked" + tail
        return r
    if generated_only and len(generated_only) == checked:
        r.verdict = NOT_APPLICABLE
        r.note = (
            f"{GENERATED_DOCS_PREFIX}* is generated from the DECLARE description; "
            "no hand-written page mentions these names yet — nothing for the PR to change" + tail
        )
        return r
    r.verdict = SATISFIED
    if generated_only:
        r.note = (
            f"{len(generated_only)} name(s) have no mention yet; their reference page is generated"
        )
    r.note = (r.note + tail).lstrip("; ")
    return r


# ---------------------------------------------------------------- error codes (rule 3)


@dataclass
class ErrorCodeUse:
    path: str
    name: str
    line: int
    text: str


def error_code_uses(diff: Diff) -> list[ErrorCodeUse]:
    """New `ErrorCodes::NAME` uses in C++ under src/, programs/, base/,
    utils/ — one per (file, name), first added line; comment lines and the
    namespace's own API names are skipped (check_cpp.sh's rule 04)."""
    out: list[ErrorCodeUse] = []
    for path, fd in diff.files.items():
        if fd.status == "D" or path == ERROR_CODES_REGISTRY or not _ERROR_CODE_FILE_RE.match(path):
            continue
        seen: set[str] = set()
        for ln, text in fd.added:
            if text.lstrip().startswith("//"):
                continue
            for m in _ERROR_CODE_USE_RE.finditer(text):
                name = m.group("name")
                if name in seen or name in _ERROR_CODE_EXEMPT:
                    continue
                seen.add(name)
                out.append(ErrorCodeUse(path, name, ln, text))
    return out


def extern_pattern(name: str) -> str:
    return f"extern const int {name};"


def rule_error_code_declared(
    uses: list[ErrorCodeUse],
    diff: Diff,
    declared_in_file: dict[tuple[str, str], bool | None],
) -> RuleResult:
    """`declared_in_file[(path, name)]`: whether the file's post-image (or its
    pre-image plus the diff) carries `extern const int NAME;`; None when the
    file could not be read. A declaration added in the diff itself decides
    without a read."""
    r = RuleResult("error_code_declared")
    if not uses:
        r.verdict, r.note = NOT_APPLICABLE, "no new ErrorCodes:: use in the diff"
        return r
    missing: list[ErrorCodeUse] = []
    unread: list[ErrorCodeUse] = []
    for u in uses:
        pat = extern_pattern(u.name)
        added = next(((ln, t) for ln, t in diff.added_in(u.path) if pat in t), None)
        if added:
            r.evidence.append(ev(u.path, added[0], added[1], error_code=u.name, where="diff"))
            continue
        removed_lines = diff.files[u.path].removed if u.path in diff.files else []
        removed = any(pat in t for _ln, t in removed_lines)
        state = declared_in_file.get((u.path, u.name))
        if state is None:
            unread.append(u)
        elif state and not removed:
            r.evidence.append(ev(u.path, 0, pat, error_code=u.name, where="file"))
        else:
            missing.append(u)
    if missing:
        r.verdict = VIOLATED
        r.evidence = [ev(u.path, u.line, u.text, error_code=u.name) for u in missing] + r.evidence
        r.note = (
            f"{len(missing)} ErrorCodes:: name(s) used without `extern const int NAME;` "
            "in the same file (check_cpp.sh rule 04: undefined ErrorCodes)"
        )
        if unread:
            r.epistemic = LOWER_BOUND
        return r
    if unread:
        r.verdict = UNKNOWN
        r.evidence = [
            ev(u.path, u.line, u.text, error_code=u.name, where="file_unread") for u in unread
        ] + r.evidence
        r.note = "the touched file(s) could not be read from the mirror or the index"
        return r
    r.verdict = SATISFIED
    return r


def summary(rules: list[RuleResult]) -> dict[str, int]:
    out = dict.fromkeys(VERDICTS, 0)
    for r in rules:
        out[r.verdict] = out.get(r.verdict, 0) + 1
    return out


