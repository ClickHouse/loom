"""namespace.rollback — return a namespace's memory heads to an instant.

Head-state rollback over loom.memory_versions: for every key whose live head differs from the
highest version stamped at or before `as_of`, that older version is re-inserted as a new head
(every column carried forward, at a version above the key's head so it wins FINAL); a key
that did not exist at `as_of` is tombstoned. Embedding rows are written as `embedding_dim = 0` stubs
carrying the reinstated text, which the embedding worker drains (the same route
memory.copy_to and the orphan reconciler use), so search converges on the reinstated content
without an inline embed here.

Not exact-state rollback: triples, records, summaries and aggregates are
regenerated by their own workers from the new heads. The dry run (default)
reports the plan without writing.
"""

from __future__ import annotations

import logging
from datetime import UTC, datetime

from server.core.ch import get_client
from server.core.errors import ValidationError
from server.identity.api.models import (
    NamespaceRollbackInput,
    NamespaceRollbackOutput,
)
from server.memory.app import namespace_rollback as memory_rollback
from server.memory.domain import rollback as svc

log = logging.getLogger(__name__)

_SAMPLE = 20


def _naive_utc(ts: datetime) -> datetime:
    if ts.tzinfo is not None:
        ts = ts.astimezone(UTC).replace(tzinfo=None)
    return ts.replace(microsecond=0)


async def handle_namespace_rollback(
    input: NamespaceRollbackInput,
) -> NamespaceRollbackOutput:
    from server.identity.app.namespace import resolve_subject
    from server.observability import audit as _audit

    now = datetime.now(UTC)
    as_of = input.as_of if input.as_of.tzinfo else input.as_of.replace(tzinfo=UTC)
    if as_of > now:
        raise ValidationError("as_of is in the future; a rollback targets a past instant")
    version_at = svc.version_at(as_of)

    ch = get_client()
    earliest = await memory_rollback.earliest_version(input.org, input.namespace, ch=ch)
    if earliest == 0:
        raise ValidationError(
            f"{input.org}/{input.namespace} has no version history to roll back to"
        )
    if version_at < earliest:
        earliest_at = datetime.fromtimestamp(earliest / 1_000_000_000, tz=UTC)
        raise ValidationError(
            "as_of predates this namespace's version history "
            f"(earliest {earliest_at.isoformat()}); rolling back before it would "
            "tombstone every key"
        )

    rows = await memory_rollback.change_rows(
        input.org,
        input.namespace,
        version_at,
        memory_keys=input.memory_keys,
        limit=input.max_keys,
        ch=ch,
    )
    truncated = len(rows) > input.max_keys
    plan = svc.plan_rollback(rows[: input.max_keys])
    sample = [a.as_dict() for a in (plan.reinstate + plan.remove)[:_SAMPLE]]

    out = NamespaceRollbackOutput(
        dry_run=input.dry_run,
        as_of=as_of,
        version_at=version_at,
        reinstate=len(plan.reinstate),
        remove=len(plan.remove),
        skipped_no_head=plan.skipped_no_head,
        skipped_already_gone=plan.skipped_already_gone,
        truncated=truncated,
        sample=sample,
    )
    if input.dry_run or plan.changes == 0:
        return out

    applied_at = _naive_utc(now)
    applied = memory_rollback.Applied()
    completed = False
    try:
        await memory_rollback.apply_rollback(
            input.org, input.namespace, plan, applied_at=applied_at, ch=ch, applied=applied
        )
        completed = True
    finally:
        # Audited with what landed, a rollback a 503 cut off after its first batches too.
        if completed or applied.reinstated or applied.removed:
            await _audit.emit(
                event_type="namespace.rollback",
                org=input.org,
                namespace=input.namespace,
                actor=resolve_subject(),
                subject={
                    "as_of": as_of.isoformat(),
                    "version_at": version_at,
                    "reinstate": applied.reinstated,
                    "remove": applied.removed,
                    # False: an error stopped it after these landed.
                    "completed": completed,
                    "truncated": truncated,
                    "memory_keys": input.memory_keys or [],
                },
            )
    # A key erased, or deleted, since the plan was left as the plan leaves one.
    out.skipped_no_head += out.reinstate - applied.reinstated
    out.skipped_already_gone += out.remove - applied.removed
    out.reinstate, out.remove = applied.reinstated, applied.removed
    out.applied_at = applied_at
    return out
