"""namespace.rollback — return a namespace's memories to what they were at an instant.

With the journal on (`memory_bitemporal_enabled`), planned and applied in the bi-temporal
journal (`server.memory.app.namespace_rollback`):
every key whose served claims as known at `as_of` differ from what it serves now gets
one commit that serves again what it served then, spans, plans and kinds as they were;
a key that served nothing then is retracted. The current-state rows, their search
projections and the high fence follow those commits as after any amendment.

Triples, records, summaries and aggregates are regenerated by their own workers. The
dry run (default) reports the plan without writing.

With the journal off it is head-state rollback over loom.memory_versions
(`server.memory.app.namespace_rollback_rows`): for every key whose live head differs from
the highest version stamped at or before `as_of`, that older version is re-inserted as a
new head (every column carried forward, a fresh version stamp so it wins FINAL); a key
that did not exist at `as_of` is tombstoned. Embedding rows are written as
`embedding_dim = 0` stubs carrying the reinstated text, which the embedding worker drains.
"""

from __future__ import annotations

import logging
from dataclasses import replace
from datetime import UTC, datetime

from server.core.ch import get_client
from server.core.errors import ValidationError
from server.core.feature_modes import bitemporal_on
from server.identity.api.models import (
    NamespaceRollbackInput,
    NamespaceRollbackOutput,
)
from server.memory.app import namespace_rollback as memory_rollback
from server.memory.app import namespace_rollback_rows as row_rollback
from server.memory.app import temporal_publisher as publisher
from server.memory.domain import rollback as svc

log = logging.getLogger(__name__)

_SAMPLE = 20


def _naive_utc(ts: datetime) -> datetime:
    if ts.tzinfo is not None:
        ts = ts.astimezone(UTC).replace(tzinfo=None)
    return ts.replace(microsecond=0)


async def handle_namespace_rollback(
    input: NamespaceRollbackInput,
) -> NamespaceRollbackOutput:
    from server.identity.app.namespace import resolve_subject
    from server.observability import audit as _audit

    now = datetime.now(UTC)
    as_of = input.as_of if input.as_of.tzinfo else input.as_of.replace(tzinfo=UTC)
    if as_of > now:
        raise ValidationError("as_of is in the future; a rollback targets a past instant")
    if not bitemporal_on():
        return await _rollback_rows(input, as_of, now)
    plan = await memory_rollback.plan(
        input.org, input.namespace, as_of, memory_keys=input.memory_keys, limit=input.max_keys
    )
    if plan.first_at is None:
        raise ValidationError(f"{input.org}/{input.namespace} has no history to roll back to")
    if as_of < plan.first_at:
        raise ValidationError(
            "as_of predates this namespace's history "
            f"(earliest {plan.first_at.isoformat()}); rolling back before it would "
            "remove every key"
        )
    changes = plan.changes
    planned = [c for c in changes if not c.refused]
    out = NamespaceRollbackOutput(
        dry_run=input.dry_run,
        as_of=as_of,
        reinstate=sum(c.action == "reinstate" for c in planned),
        remove=sum(c.action == "remove" for c in planned),
        left_out=len(changes) - len(planned),
        truncated=plan.truncated,
        sample=[c.sample() for c in changes[:_SAMPLE]],
    )
    if input.dry_run or not planned:
        return out

    receipts = await memory_rollback.apply(input.org, input.namespace, changes)
    committed = {r.ident for r in receipts if r.commit_seq}
    done = [c for c in planned if c.ident in committed]
    out.reinstate = sum(c.action == "reinstate" for c in done)
    out.remove = sum(c.action == "remove" for c in done)
    # Refused, or a lock in force refused the change: the key keeps its claims.
    out.left_out = len(changes) - len(done)
    # The same keys as the dry run's sample, each as it ended.
    out.sample = [
        (c if c.ident in committed else replace(c, refused=True)).sample()
        for c in changes[:_SAMPLE]
    ]
    out.applied_at = datetime.now(UTC)
    out.read_token = publisher.read_token(receipts)
    # Audited as soon as it is committed: the rows that follow are a projection.
    await _audit.emit(
        event_type="namespace.rollback",
        org=input.org,
        namespace=input.namespace,
        actor=resolve_subject(),
        subject={
            "as_of": as_of.isoformat(),
            "reinstate": out.reinstate,
            "remove": out.remove,
            "left_out": out.left_out,
            "truncated": plan.truncated,
            "memory_keys": input.memory_keys or [],
            "commit_seqs": sorted(r.commit_seq for r in receipts if r.commit_seq),
        },
    )
    try:
        await memory_rollback.project(input.org, input.namespace, receipts)
    except Exception as e:  # noqa: BLE001 — committed and audited: the reconciler follows
        # The current rows lag the commits; the reconciler brings them in line.
        out.current_rows_pending = True
        log.warning("namespace.rollback: current rows left to the reconciler: %s", e)
    return out


async def _rollback_rows(
    input: NamespaceRollbackInput, as_of: datetime, now: datetime
) -> NamespaceRollbackOutput:
    """The rollback without the journal: version rows re-emitted as heads."""
    from server.identity.app.namespace import resolve_subject
    from server.observability import audit as _audit

    version_at = svc.version_at(as_of)

    ch = get_client()
    earliest = await row_rollback.earliest_version(input.org, input.namespace, ch=ch)
    if earliest == 0:
        raise ValidationError(
            f"{input.org}/{input.namespace} has no version history to roll back to"
        )
    if version_at < earliest:
        earliest_at = datetime.fromtimestamp(earliest / 1_000_000_000, tz=UTC)
        raise ValidationError(
            "as_of predates this namespace's version history "
            f"(earliest {earliest_at.isoformat()}); rolling back before it would "
            "tombstone every key"
        )

    rows = await row_rollback.change_rows(
        input.org,
        input.namespace,
        version_at,
        memory_keys=input.memory_keys,
        limit=input.max_keys,
        ch=ch,
    )
    truncated = len(rows) > input.max_keys
    plan = svc.plan_rollback(rows[: input.max_keys])
    sample = [a.as_dict() for a in (plan.reinstate + plan.remove)[:_SAMPLE]]

    out = NamespaceRollbackOutput(
        dry_run=input.dry_run,
        as_of=as_of,
        version_at=version_at,
        reinstate=len(plan.reinstate),
        remove=len(plan.remove),
        skipped_no_head=plan.skipped_no_head,
        skipped_already_gone=plan.skipped_already_gone,
        truncated=truncated,
        sample=sample,
    )
    if input.dry_run or plan.changes == 0:
        return out

    applied_at = _naive_utc(now)
    await row_rollback.apply_rollback(
        input.org, input.namespace, plan, applied_at=applied_at, ch=ch
    )

    caller = resolve_subject()
    await _audit.emit(
        event_type="namespace.rollback",
        org=input.org,
        namespace=input.namespace,
        actor=caller,
        subject={
            "as_of": as_of.isoformat(),
            "version_at": version_at,
            "reinstate": len(plan.reinstate),
            "remove": len(plan.remove),
            "truncated": truncated,
            "memory_keys": input.memory_keys or [],
        },
    )
    out.applied_at = applied_at
    return out
