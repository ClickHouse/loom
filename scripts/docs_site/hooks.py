"""MkDocs hooks for the documentation site built from docs/.

Each page's meta description is its first sentence, the line llms.txt lists for it, so a
search result shows the answer the page opens with. An inline Markdown link or image that
leaves docs/ (source files, the README, llms.txt) points at the file on GitHub instead of
a missing page; links in code blocks and code spans are left as written, and
reference-style links are not rewritten (the docs use inline links). The sidebar follows
llms.txt's section order, with Overview and Quickstart first in Getting started, and a
generated page gets no edit button (its source is the generator, not the page).
"""

from __future__ import annotations

import html
import posixpath
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from scripts.codegen.page_summary import SECTIONS, page_summary  # noqa: E402

BLOB = "https://github.com/ClickHouse/loom/blob/main/"
RAW = "https://raw.githubusercontent.com/ClickHouse/loom/main/"
# The generators' whole-page markers; a page with generated regions ("not this region")
# keeps its edit button.
_WHOLLY_GENERATED = re.compile(
    r"<!-- Generated by [^>]*not this page|^This page is generated from", re.MULTILINE
)
# Scanned left to right: a fenced block (indented ones too) or a code span is kept as
# written, an inline link or image may be rewritten. A link's text may hold code spans;
# an image inside a link is matched as the image.
_TOKEN = re.compile(
    r"(?P<fence>^[ \t]*(?P<mark>`{3,}|~{3,})[^\n]*\n.*?^[ \t]*(?P=mark)[ \t]*$)"
    r"|(?P<link>(?P<bang>!?)(?P<text>\[(?:`[^`\n]*`|!(?!\[)|[^\]`!])*\]\()"
    r"(?P<target>[^)\s#]+)(?P<anchor>#[^)\s]*)?(?P<tail>(?:\s+\"[^\"]*\")?\)))"
    r"|(?P<code>``(?:[^`]|`(?!`))+?``|`(?:[^`\n]|\n(?![ \t]*\n))+`)",
    re.DOTALL | re.MULTILINE,
)


def on_page_markdown(markdown, page, config, files):
    _title, summary = page_summary(Path(page.file.abs_src_path))
    description = page.meta.get("description") or summary.replace("`", "")
    if description.endswith(":"):
        description = description[:-1] + "."  # an opening sentence that leads into a list
    if description:
        # The theme writes the description into its <meta> attribute unescaped.
        page.meta["description"] = html.escape(description)
    if _WHOLLY_GENERATED.search(markdown):
        page.edit_url = None
    page_dir = posixpath.dirname("docs/" + page.file.src_uri)

    def rewrite(m: re.Match[str]) -> str:
        if not m.group("link"):
            return m.group(0)
        target = m.group("target")
        if "://" in target or target.startswith(("mailto:", "/")):
            return m.group(0)
        resolved = posixpath.normpath(posixpath.join(page_dir, target))
        if resolved.startswith("docs/"):
            return m.group(0)
        base = RAW if m.group("bang") else BLOB
        anchor = m.group("anchor") or ""
        return f"{m.group('bang')}{m.group('text')}{base}{resolved}{anchor}{m.group('tail')}"

    return _TOKEN.sub(rewrite, markdown)


_SECTION_RANK = {folder: rank for rank, (_title, folder) in enumerate(SECTIONS)}
_FIRST_PAGES = ("getting-started/overview.md", "getting-started/quickstart.md")


def _folder(section) -> str:
    first = next((c for c in section.children if c.is_page), None)
    return first.file.src_uri.split("/", 1)[0] if first else ""


def _top_key(item) -> tuple[int, str]:
    """The home page, then the sections in llms.txt's order, then loose pages (FAQ, glossary)."""
    if item.is_page:
        uri = item.file.src_uri
        return (-1, uri) if uri == "index.md" else (len(SECTIONS) + 1, uri)
    return (_SECTION_RANK.get(_folder(item), len(SECTIONS)), str(item.title))


def _child_key(item) -> tuple[int, int, str]:
    """Inside a section: its index page, the lead pages, the other pages, then subsections."""
    if not item.is_page:
        return (1, 0, str(item.title))
    uri = item.file.src_uri
    if uri.endswith("/index.md"):
        return (0, 0, uri)
    if uri in _FIRST_PAGES:
        return (0, 1 + _FIRST_PAGES.index(uri), uri)
    return (0, 1 + len(_FIRST_PAGES), uri)


def _pages(items) -> list:
    out = []
    for item in items:
        out.extend(_pages(item.children) if item.is_section else [item])
    return out


def on_nav(nav, config, files):
    nav.items.sort(key=_top_key)
    for item in nav.items:
        if item.is_section:
            item.children.sort(key=_child_key)
    # MkDocs links each page to its neighbours before this event; relink them in the new order.
    nav.pages = _pages(nav.items)
    for i, page in enumerate(nav.pages):
        page.previous_page = nav.pages[i - 1] if i else None
        page.next_page = nav.pages[i + 1] if i + 1 < len(nav.pages) else None
    return nav
