"""Write `schemas/schema.sql`: the `loom.*` tables and views a replay of
`schemas/migrations/` leaves.

    make schema-dump      # python -m scripts.ops.dump_schema
    make schema-check     # python -m scripts.ops.dump_schema --check (CI)

Run it against a fresh ClickHouse of the release CI runs, the latest (see
`dev/ci_start_clickhouse.sh`), after `loom migrate`: the dump is what that
server prints, so another release, a server without the `Quantized` codec, or
a database that holds rebuild twins dumps differently. `--check` names the
release it dumped from, so a new release that prints DDL differently is told
from a schema change.

It connects with the `LOOM_CH_*` settings `loom migrate` uses. The dump is
built in full before anything is written: a failed dump leaves the file as it
was, and `--check` never writes. Internal tables (`_migrations`, leading `_`
or `.` names) and `vector_similarity` indexes added by hand are left out.
"""

from __future__ import annotations

import argparse
import dataclasses
import difflib
import itertools
import re
import sys
from pathlib import Path
from typing import Any

if (_ROOT := str(Path(__file__).resolve().parents[2])) not in sys.path:  # run as a file
    sys.path.insert(0, _ROOT)

from scripts.codegen.common import ROOT, GeneratedFile

DATABASE = "loom"  # every migration addresses loom.<table>, whatever LOOM_CH_DATABASE says
TARGET = GeneratedFile(ROOT / "schemas" / "schema.sql", "make schema-dump")
# The dump with the bi-temporal journal on (LOOM_MEMORY_BITEMPORAL_ENABLED=true): its
# migration is dormant otherwise, so the default dump never holds its objects.
TEMPORAL_TARGET = GeneratedFile(
    ROOT / "schemas" / "schema_temporal.sql", "LOOM_MEMORY_BITEMPORAL_ENABLED=true make schema-dump"
)


def _target_for_mode() -> GeneratedFile:
    from server.settings import settings

    return TEMPORAL_TARGET if settings.memory_bitemporal_enabled else TARGET


DIFF_LINES = 40


def list_objects(client: Any) -> tuple[list[str], list[str]]:
    """(tables, materialized views), each sorted by name, internals excluded."""
    rows = client.query(
        "SELECT name, engine FROM system.tables "
        "WHERE database = {db:String} AND name NOT LIKE '\\_%' AND name NOT LIKE '.%' "
        "ORDER BY name",
        parameters={"db": DATABASE},
    ).result_rows
    tables = [str(n) for n, engine in rows if engine != "MaterializedView"]
    views = [str(n) for n, engine in rows if engine == "MaterializedView"]
    return tables, views


_VECTOR_INDEX_RE = re.compile(
    r"^\s*INDEX\s+\S+\s+\S+\s+TYPE\s+vector_similarity\b.*$",
    re.IGNORECASE,
)


def strip_runtime_indexes(ddl: str) -> str:
    """`ddl` without `vector_similarity` index lines, and without the comma a
    removed last item leaves. No migration declares one; a deployment that adds
    one by hand still dumps the migrated schema."""
    lines = [ln for ln in ddl.splitlines() if not _VECTOR_INDEX_RE.match(ln)]
    out: list[str] = []
    for i, ln in enumerate(lines):
        nxt = lines[i + 1].lstrip() if i + 1 < len(lines) else ""
        if ln.rstrip().endswith(",") and nxt.startswith(")"):
            ln = ln.rstrip()[:-1]
        out.append(ln)
    return "\n".join(out)


_CREATE_PREFIX_RE = re.compile(
    r"^(CREATE\s+(?:TABLE|MATERIALIZED VIEW|VIEW))\s+",
    re.IGNORECASE,
)


def add_if_not_exists(ddl: str) -> str:
    """`SHOW CREATE` prints a plain CREATE; the dump states it idempotently."""
    return _CREATE_PREFIX_RE.sub(r"\1 IF NOT EXISTS ", ddl, count=1)


def header(tables: int, views: int, name: str = "schema.sql") -> str:
    mode = (
        "\n-- with the bi-temporal journal on (LOOM_MEMORY_BITEMPORAL_ENABLED=true; its\n"
        "-- migration is dormant otherwise)"
        if name == "schema_temporal.sql"
        else ""
    )
    return f"""-- schemas/{name}
--
-- Reference dump of `{DATABASE}.*`: what replaying schemas/migrations/*.sql
-- produces{mode}, auto-generated by scripts/ops/dump_schema.py from a live
-- ClickHouse that has every migration applied. Read it to see the current
-- shape of a table or view.
--
-- This is NOT an install path. Applying it directly skips the migration
-- ledger and the rewrites the runner makes at apply time (session settings,
-- server-specific clauses). Install or upgrade with:
--     loom migrate
--
-- This file is regenerated whenever migrations change:
--     make schema-dump
--
-- Do NOT hand-edit. Edit schemas/migrations/*.sql and re-dump.
-- CI verifies this file matches what migrations would produce.
--
-- Counts: {tables} tables + {views} materialized views.

CREATE DATABASE IF NOT EXISTS `{DATABASE}`;
"""


def section(title: str, statements: list[tuple[str, str]]) -> list[str]:
    rule = "-- " + "=" * 70
    out = [rule, f"-- {title} ({len(statements)})", rule + "\n"]
    for name, ddl in statements:
        out.append(f"-- {DATABASE}.{name}")
        out.append(add_if_not_exists(strip_runtime_indexes(ddl)) + ";\n")
    return out


def render(
    tables: list[tuple[str, str]], views: list[tuple[str, str]], name: str = "schema.sql"
) -> str:
    """The file from `(name, SHOW CREATE)` pairs. Pure."""
    out = [header(len(tables), len(views), name)]
    out += section("Tables", tables)
    out += section("Materialized views", views)
    return "\n".join(out)


def show_create(client: Any, name: str) -> tuple[str, str]:
    rows = client.query(f"SHOW CREATE TABLE `{DATABASE}`.`{name}`").result_rows
    if not rows:
        raise RuntimeError(f"no DDL for {DATABASE}.{name}")
    return name, str(rows[0][0])


def dump(client: Any, name: str = "schema.sql") -> str:
    tables, views = list_objects(client)
    return render(
        [show_create(client, n) for n in tables],
        [show_create(client, n) for n in views],
        name,
    )


def diff_head(target: GeneratedFile, fresh: str, limit: int = DIFF_LINES) -> str:
    current = target.path.read_text(encoding="utf-8") if target.path.exists() else ""
    lines = difflib.unified_diff(
        current.splitlines(keepends=True),
        fresh.splitlines(keepends=True),
        fromfile=target.display,
        tofile="fresh dump",
    )
    return "".join(itertools.islice(lines, limit))


def build(name: str = "schema.sql") -> tuple[str, str]:
    """The dump, and the ClickHouse release that printed it."""
    from server.core.schema.migrate import client

    c = client()
    try:
        return dump(c, name), str(c.query("SELECT version()").result_rows[0][0])
    finally:
        c.close()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--check", action="store_true", help="exit 1 when the file is stale")
    default = _target_for_mode()
    ap.add_argument(
        "--out", type=Path, default=default.path, help=f"default {default.display} (by mode)"
    )
    args = ap.parse_args(argv)
    target = dataclasses.replace(default, path=args.out)
    try:
        text, version = build(args.out.name)
    except Exception as e:  # noqa: BLE001 - any failure is a failed dump, reported as one
        print(f"schema dump failed: {e}", file=sys.stderr)
        return 1
    if not args.check and target.is_current(text):
        print(f"{target.display} is current")
        return 0
    rc = target.sync(text, check=args.check)
    if rc:
        sys.stderr.write(f"dumped from ClickHouse {version}\n" + diff_head(target, text))
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
