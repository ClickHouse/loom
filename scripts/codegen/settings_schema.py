"""Generate schemas/loom-settings.schema.json, the JSON Schema of the YAML settings file.

`version` and a flat `settings` mapping whose properties are the settings fields with
their types, bounds, defaults and comments. Secrets are left out: the file refuses them
(server/settings/_file.py). Editors validate the file with a first line of
`# yaml-language-server: $schema=<path or URL of this file>`.

    python scripts/codegen/settings_schema.py          # rewrite the schema
    python scripts/codegen/settings_schema.py --check  # exit 1 when it is stale
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:  # run as a file
    sys.path.insert(0, str(ROOT))

from scripts.codegen.common import GeneratedFile, generator_main  # noqa: E402
from server.settings import Settings  # noqa: E402
from server.settings._describe import descriptions  # noqa: E402
from server.settings._env import is_secret_field  # noqa: E402
from server.settings._file import VERSIONS  # noqa: E402

COMMAND = "python scripts/codegen/settings_schema.py"
SCHEMA_ID = (
    "https://raw.githubusercontent.com/ClickHouse/loom/main/schemas/loom-settings.schema.json"
)


def schema() -> dict[str, Any]:
    fields = Settings.model_json_schema()["properties"]
    about = descriptions(Settings)
    properties: dict[str, Any] = {}
    for name in sorted(fields):
        if is_secret_field(name):
            continue
        prop = {k: v for k, v in fields[name].items() if k != "title"}
        if about.get(name):
            prop["description"] = about[name]
        properties[name] = prop
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": SCHEMA_ID,
        "title": "Loom settings file",
        "description": (
            "Server settings, one per LOOM_<NAME> environment variable, named in "
            "lowercase. The environment and the dotenv file win over this file; "
            "secrets are refused here. Generated by " + COMMAND + "."
        ),
        "type": "object",
        "additionalProperties": False,
        "required": ["version"],
        "properties": {
            "version": {"enum": list(VERSIONS), "description": "The file format version."},
            "settings": {
                "type": "object",
                "additionalProperties": False,
                "properties": properties,
            },
        },
    }


def render() -> str:
    return json.dumps(schema(), indent=2, ensure_ascii=False) + "\n"


TARGET = GeneratedFile(ROOT / "schemas" / "loom-settings.schema.json", COMMAND)


def main(argv: list[str] | None = None) -> int:
    return generator_main(__doc__, TARGET, render, argv)


if __name__ == "__main__":
    raise SystemExit(main())
