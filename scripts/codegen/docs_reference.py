CLI_SNAPSHOT = ROOT / "tests" / "unit" / "snapshots" / "cli_tree.json"


def _flags(node: dict) -> str:
    names = []
    for a in node.get("arguments", []):
        opts = a.get("option_strings") or []
        if a.get("action") in ("_HelpAction", "_SubParsersAction", "_VersionAction"):
            continue
        names.append(f"`{opts[-1]}`" if opts else f"`<{a.get('metavar') or a['dest']}>`")
    return ", ".join(names)


def _cli_rows(node: dict, out: list[str]) -> None:
    for a in node.get("arguments", []):
        subs = a.get("subcommands")
        if not subs:
            continue
        helps = {c.get("dest"): c.get("help") for c in a.get("choices_help") or []}
        for name, child in subs.items():
            summary = helps.get(name) or child.get("description") or ""
            out.append(
                f"| `{child['prog']}` | {_cell(_first_sentence(summary))} | {_flags(child)} |"
            )
            _cli_rows(child, out)


def render_cli() -> str:
    tree = json.loads(CLI_SNAPSHOT.read_text(encoding="utf-8"))
    out = ["| Command | Summary | Arguments and flags |", "| --- | --- | --- |"]
    _cli_rows(tree, out)
    return "\n".join(out) + "\n"


# --- errors -------------------------------------------------------------------

_CODE_LITERAL = re.compile(r"^[A-Z][A-Z0-9_]{3,}$")


def _code_literals() -> dict[str, set[str]]:
    """Every `"code": "X"` dict entry and `code="X"` keyword under server/."""
    found: dict[str, set[str]] = defaultdict(set)
    for path in sorted((ROOT / "server").rglob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        rel = path.relative_to(ROOT).as_posix()
        for node in ast.walk(tree):
            pairs: list[tuple[ast.AST, ast.AST]] = []
            if isinstance(node, ast.Dict):
                pairs = [(k, v) for k, v in zip(node.keys, node.values, strict=False) if k]
            elif isinstance(node, ast.Call):
                pairs = [(ast.Constant(k.arg), k.value) for k in node.keywords if k.arg]
            for k, v in pairs:
                if (
                    isinstance(k, ast.Constant)
                    and k.value in ("code", "error_code")
                    and isinstance(v, ast.Constant)
                    and isinstance(v.value, str)
                    and _CODE_LITERAL.match(v.value)
                ):
                    found[v.value].add(rel)
    return found


def _typed_errors() -> dict[str, tuple[int, str, str]]:
    """Classes under server/ that declare both `code = "X"` and `status_code = N`: the
    `LoomServerError` family. Read from the source, so the table does not depend on
    which modules happen to be imported."""
    typed: dict[str, tuple[int, str, str]] = {}
    for path in sorted((ROOT / "server").rglob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        module = path.relative_to(ROOT).with_suffix("").as_posix().replace("/", ".")
        for cls in (n for n in ast.walk(tree) if isinstance(n, ast.ClassDef)):
            attrs: dict[str, object] = {}
            for stmt in cls.body:
                target = stmt.target if isinstance(stmt, ast.AnnAssign) else None
                if isinstance(stmt, ast.Assign) and len(stmt.targets) == 1:
                    target = stmt.targets[0]
                value = getattr(stmt, "value", None)
                if isinstance(target, ast.Name) and isinstance(value, ast.Constant):
                    attrs[target.id] = value.value
            code, status = attrs.get("code"), attrs.get("status_code")
            if isinstance(code, str) and _CODE_LITERAL.match(code) and isinstance(status, int):
                doc = _first_sentence(ast.get_docstring(cls))
                typed.setdefault(code, (status, doc, f"{module}.{cls.name}"))
    return typed


