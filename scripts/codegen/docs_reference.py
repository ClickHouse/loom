def _op_anchor(name: str) -> str:
    """The GitHub slug of an op heading such as `## memory.set`."""
    return re.sub(r"[^\w\- ]", "", name.lower())


def _type_name(annotation: object) -> str:
    """A type as a reader writes it (`str | None`, `list[str]`, `Literal['a', 'b']`),
    built from the annotation's structure so every Python version prints it the same."""
    import types
    import typing

    if annotation is type(None):
        return "None"
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if origin is typing.Annotated:
        return _type_name(args[0])
    if origin is typing.Literal:
        return "Literal[" + ", ".join(repr(a) for a in args) + "]"
    if origin in (typing.Union, types.UnionType):
        return " | ".join(_type_name(a) for a in args)
    if origin is not None:
        name = getattr(origin, "__name__", str(origin))
        return f"{name}[{', '.join(_type_name(a) for a in args)}]" if args else name
    if annotation is typing.Any:
        return "Any"
    return getattr(annotation, "__name__", str(annotation).replace("typing.", ""))


def _class_comments(cls: type) -> dict[str, str]:
    """Field name → the comment written above it (and after it) in the model's source,
    for the class and every base class defined under server/."""
    import inspect

    out: dict[str, str] = {}
    for klass in reversed(cls.__mro__):
        module = getattr(klass, "__module__", "")
        if not module.startswith("server."):
            continue
        try:
            path = inspect.getsourcefile(klass)
        except TypeError:
            continue
        if not path:
            continue
        src = Path(path).read_text(encoding="utf-8")
        lines = src.splitlines()
        tree = ast.parse(src)
        for node in ast.walk(tree):
            if not (isinstance(node, ast.ClassDef) and node.name == klass.__name__):
                continue
            for stmt in node.body:
                if not (isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name)):
                    continue
                above: list[str] = []
                i = stmt.lineno - 2
                while i >= 0 and lines[i].strip().startswith("#"):
                    above.append(lines[i].strip().lstrip("#").strip())
                    i -= 1
                tail = re.search(r"\s#\s?(.*)$", lines[(stmt.end_lineno or stmt.lineno) - 1])
                trailing = tail.group(1).strip() if tail and "noqa" not in tail.group(1) else ""
                text = " ".join([*reversed(above), trailing]).strip()
                if text:
                    out[stmt.target.id] = text
    return out


# The identity tuple and the consumer tag mean the same thing on every op.
_COMMON_FIELDS = {
    "org": "The tenant (first element of the identity tuple).",
    "namespace": "The namespace the op reads or writes.",
    "agent": "The writing or reading agent; `'-'` or `'*'` means any agent where the op allows it.",
    "user_id": "The end user the row belongs to; `'-'` for none.",
    "session_id": "The session or conversation the row belongs to; `'-'` for none.",
    "run_id": "The agent run (task scope) the call belongs to; `'-'` for none.",
    "consumer": "The calling integration's tag, recorded on the ledger row.",
}


def _field_rows(model: type, with_default: bool) -> list[str]:
    from pydantic_core import PydanticUndefined

    comments = _class_comments(model)
    rows = []
    for name, info in model.model_fields.items():  # type: ignore[attr-defined]
        meaning = info.description or comments.get(name, "") or _COMMON_FIELDS.get(name, "")
        cells = [f"`{info.alias or name}`", f"`{_cell(_type_name(info.annotation))}`"]
        if with_default:
            if info.is_required():
                default = "required"
            elif info.default_factory is not None:
                default = "*(computed)*"
            elif info.default is PydanticUndefined:
                default = ""
            else:
                text = repr(info.default)
                default = f"`{_cell(text if len(text) <= 40 else text[:37] + '…')}`"
            cells.append(default)
        cells.append(_cell(_first_sentence(meaning, 240)))
        rows.append("| " + " | ".join(cells) + " |")
    return rows


