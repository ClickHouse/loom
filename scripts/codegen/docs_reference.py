"""Generate the reference tables under docs/reference/ from the code that defines them.

Each target page is hand-written prose with one or more generated regions:

    <!-- BEGIN GENERATED: operations -->
    ...rendered here...
    <!-- END GENERATED: operations -->

Only the text between a pair of markers is rewritten, so a page can explain the
table it carries. A region's name picks its renderer:

- `operations`: every registered op, grouped, from `server.operations.registry.ALL_OPERATIONS`
- `workers`: the background loops in `server/workers/registry.py` (`_WORKERS`)
- `cli`: the `loom` command tree, from the committed parser snapshot
  `tests/unit/snapshots/cli_tree.json` (a unit test keeps it equal to the parser)
- `errors`: the typed errors in `server/core/errors.py` and every other `"code"`
  literal the server answers with
- `schema`: the tables, views and materialized views in `schemas/schema.sql`
- `status_ops`, `status_switches`: each op group's stable and experimental ops (op
  `maturity`), and every boolean setting in `server/settings/catalog.py` that loads false

It also writes `llms.txt` at the repository root (every doc page with its outcome line, for
agents), and one fully generated page per op group, `docs/reference/operations/<group>.md`,
with every op's input and output fields (type, default, and the comment written above the
field in its model).

    python scripts/codegen/docs_reference.py          # rewrite the regions
    python scripts/codegen/docs_reference.py --check  # exit 1 when one is stale
"""

