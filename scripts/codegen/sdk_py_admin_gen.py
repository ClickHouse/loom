"""Generate `sdk/python/loom/admin_routes.py` — one Python method per `/v1/admin/*`
route — and the route table of docs/reference/http-api.md, from the routes themselves.

The operator routes sit outside the op registry, so `sdk_py_client_gen.py` does not
reach them. Here each route's method, path, docstring and gate come from its router:
`agent.deployment.routes.<name>(body)` posts `body` to the route as it is, named from
the endpoint (`admin_settings_set` → `settings_set`). The hand-written
`agent.deployment` methods stay the high-level layer on top.

    python scripts/codegen/sdk_py_admin_gen.py           # write the file
    python scripts/codegen/sdk_py_admin_gen.py --check   # exit 1 when it is stale (CI)
"""

from __future__ import annotations

import keyword
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:  # run as a file
    sys.path.insert(0, str(ROOT))

from scripts.codegen.common import GeneratedFile, generator_main, ruff_format  # noqa: E402

COMMAND = "python scripts/codegen/sdk_py_admin_gen.py"


@dataclass(frozen=True)
class AdminRoute:
    method: str
    path: str
    name: str
    gate: str
    doc: str


def _routers() -> list[tuple[Any, str]]:
    """Every router that serves `/v1/admin/*`, with the role its gate requires."""
    from server.identity.app import claim_release
    from server.identity.app.admin_account_routes import router as accounts
    from server.insights.app.admin_routes import admin_router, org_admin_router
    from server.insights.app.provider_routes import provider_router

    return [
        (admin_router, "platform_admin"),
        (org_admin_router, "org_admin"),
        (provider_router, "platform_admin"),
        (accounts, "platform_admin"),
        # Gated in the handler (`require_org_admin`), not on the router.
        (claim_release.router, "org_admin"),
    ]


def _name(endpoint: Any) -> str:
    name = endpoint.__name__.removeprefix("admin_")
    if not name.isidentifier() or keyword.iskeyword(name):
        raise SystemExit(f"{endpoint.__name__} has no valid Python method name")
    return name


def _first_sentence(doc: str | None) -> str:
    para = " ".join((doc or "").strip().split("\n\n")[0].split())
    m = re.search(r"(?<=[.!?])\s+(?=[A-Z`(])", para)
    return para[: m.start()] if m else para


def admin_routes() -> list[AdminRoute]:
    out: list[AdminRoute] = []
    for router, gate in _routers():
        for r in router.routes:
            if not r.path.startswith("/v1/admin/"):
                continue
            doc = _first_sentence(r.endpoint.__doc__)
            if not doc:
                raise SystemExit(f"{r.path}: its endpoint has no docstring to describe it")
            for method in sorted(r.methods - {"HEAD"}):
                out.append(AdminRoute(method, r.path, _name(r.endpoint), gate, doc))
    names = [r.name for r in out]
    if len(names) != len(set(names)):
        raise SystemExit(
            f"two admin routes map to one method: {sorted(n for n in names if names.count(n) > 1)}"
        )
    return sorted(out, key=lambda r: (r.path, r.method))


def _method(r: AdminRoute) -> list[str]:
    doc = f"`{r.method} {r.path}` ({r.gate}). {r.doc}".rstrip()
    if r.method == "GET":
        return [
            f"    async def {r.name}(self) -> Any:",
            f'        """{doc}"""',
            f'        return await self._agent.transport.request_json("GET", "{r.path}")',
            "",
        ]
    return [
        f"    async def {r.name}(self, body: dict[str, Any] | None = None) -> Any:",
        f'        """{doc}"""',
        "        return await self._agent.transport.request_json(",
        f'            "{r.method}", "{r.path}", json=body or {{}}',
        "        )",
        "",
    ]


def build() -> str:
    out = [
        f'"""GENERATED by {COMMAND} from the /v1/admin/* routers — do not edit.',
        "",
        "One method per operator route: `agent.deployment.routes.<name>(body)` sends `body`",
        "to the route as it is and returns the JSON answer. The routes need the gate each",
        "docstring names; `agent.deployment` has the curated methods over them.",
        '"""',
        "# ruff: noqa: E501",
        "",
        "from __future__ import annotations",
        "",
        "from typing import TYPE_CHECKING, Any",
        "",
        "if TYPE_CHECKING:",
        "    from loom.agent import Agent",
        "",
        '__all__ = ["AdminRoutes"]',
        "",
        "",
        "class AdminRoutes:",
        '    """The `/v1/admin/*` routes, one method each."""',
        "",
        "    # SyncAgent proxies a nested client's coroutines as blocking calls.",
        "    _loom_nested_client = True",
        "",
        "    def __init__(self, agent: Agent) -> None:",
        "        self._agent = agent",
        "",
    ]
    for r in admin_routes():
        out += _method(r)
    return ruff_format("\n".join(out).rstrip() + "\n", "sdk/python/loom/admin_routes.py")


def _cell(text: str) -> str:
    return " ".join(text.replace("|", "\\|").split())


def render_admin_routes_table() -> str:
    """The http-api.md table of the operator routes."""
    rows = [
        "| Method and path | Needs | What it is |",
        "| --- | --- | --- |",
        *(f"| `{r.method} {r.path}` | `{r.gate}` | {_cell(r.doc)} |" for r in admin_routes()),
    ]
    return "\n".join(rows)


TARGET = GeneratedFile(ROOT / "sdk" / "python" / "loom" / "admin_routes.py", COMMAND)


def main(argv: list[str] | None = None) -> int:
    return generator_main(__doc__, TARGET, build, argv)


if __name__ == "__main__":
    raise SystemExit(main())
