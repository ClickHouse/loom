"""Executable fixtures for schema shapes absent from the selected production models."""

from scripts.codegen.sdk_rust_gen import SUPPORT, Emitter, rustfmt


def build_fixture() -> str:
    em = Emitter()
    nullable = {"anyOf": [{"type": "string"}, {"type": "null"}]}
    em.model(
        "Request",
        {
            "properties": {
                "type": {"type": "string"},
                "required_null": nullable,
                "optional_null": {**nullable, "default": None},
                "label": {"type": "string", "enum": ["", "ready"], "default": "ready"},
                "union": {"anyOf": [{"type": "string"}, {"type": "integer"}]},
            },
            "required": ["type", "required_null", "union"],
        },
        request=True,
    )
    em.model(
        "Response",
        {
            "properties": {
                "required_null": nullable,
                "label": {"type": "string", "const": "ready", "default": "ready"},
            },
            "required": ["required_null"],
        },
        request=False,
    )
    em.model(
        "Defaults",
        {
            "properties": {
                "flag": {"anyOf": [{"type": "boolean"}, {"type": "null"}], "default": False},
                "count": {"anyOf": [{"type": "integer"}, {"type": "null"}], "default": 0},
                "text": {**nullable, "default": ""},
                "items": {
                    "anyOf": [{"type": "array", "items": {"type": "string"}}, {"type": "null"}],
                    "default": [],
                },
                "mapping": {
                    "anyOf": [
                        {"type": "object", "additionalProperties": {"type": "string"}},
                        {"type": "null"},
                    ],
                    "default": {},
                },
                "label": {"type": "string", "enum": ["", "ready"], "default": ""},
            },
        },
        request=False,
    )
    # SUPPORT's Integer mapping is exercised by an untagged union here.
    text = (
        "// Generated by python scripts/codegen/sdk_rust_gen.py --fixtures; do not edit.\n"
        "use serde::{Deserialize, Serialize};\n"
        + SUPPORT
        + "\n".join(em.declarations.values())
        + "\n"
        + "\n".join(em.defaults)
        + TESTS
    )
    return rustfmt(text)


TESTS = """
#[test]
fn nullable_zero_and_empty_enum_defaults_match_schema() {
    let response: Defaults = serde_json::from_str("{}").unwrap();
    assert_eq!(response.flag, Some(false));
    assert_eq!(response.count, Some(Integer::from(0)));
    assert_eq!(response.text.as_deref(), Some(""));
    assert_eq!(response.items, Some(vec![]));
    assert_eq!(response.mapping, Some(std::collections::HashMap::new()));
    assert_eq!(response.label, DefaultsLabel::Empty);
    let explicit: Defaults = serde_json::from_str(
        r#"{"flag":null,"count":null,"text":null,"items":null,"mapping":null}"#
    ).unwrap();
    assert!(explicit.flag.is_none());
    assert!(explicit.count.is_none());
    assert!(explicit.text.is_none());
    assert!(explicit.items.is_none());
    assert!(explicit.mapping.is_none());
}

#[test]
fn required_nullable_and_union_contract() {
    let request: Request = serde_json::from_str(
        r#"{"type":"job","required_null":null,"optional_null":null,"union":18446744073709551616000000000000}"#
    ).unwrap();
    assert_eq!(request.required_null, None);
    assert_eq!(request.optional_null, Some(None));
    assert!(serde_json::to_string(&request).unwrap().contains("18446744073709551616000000000000"));
    assert!(serde_json::from_str::<Request>(r#"{"type":"job","union":"value"}"#).is_err());
    assert!(serde_json::from_str::<Response>("{}").is_err());
    let response: Response = serde_json::from_str(r#"{"required_null":null}"#).unwrap();
    assert_eq!(response.label, ResponseLabel::Ready);
    assert!(serde_json::from_str::<Response>(
        r#"{"required_null":null,"label":"other"}"#
    ).is_err());
    let omitted: Request = serde_json::from_str(
        r#"{"type":"job","required_null":"value","union":"text"}"#
    ).unwrap();
    assert!(serde_json::to_value(&omitted).unwrap().get("optional_null").is_none());
    assert_eq!(serde_json::to_value(&omitted).unwrap()["union"], "text");
}
"""
