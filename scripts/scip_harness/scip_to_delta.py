# concrete method is a `function` (lang_go writes `<pkg>::Recv::Name` as one),
# an interface's method a body-less `method`, a struct field a `field`.
_GO_SCIP_KINDS: dict[str, str] = {
    "Struct": "struct",
    "Class": "struct",
    "Interface": "interface",
    "Type": "type",
    "TypeAlias": "type",
    "TypeParameter": "type",
    "Enum": "enum",
    "Field": "field",
    "Property": "field",
    "Method": "function",
    "MethodSpecification": "method",
    "AbstractMethod": "method",
    "Function": "function",
    "Constructor": "function",
    "Variable": "var",
    "Constant": "const",
    "EnumMember": "const",
}


def _go_prepass(data: bytes, scip_pb2, ctx: _GoContext) -> None:
    """Every definition's kind from the indexer's own
    SymbolInformation.kind, index-wide, before any symbol is parsed. Without
    it the descriptor loop leaves a struct field (`Stats#MaxIdleConns.`) and an
    interface method (`Conn#Query.`) with the `class` their type's `#` sets,
    and those rows rank above functions of the same bare name (the
    types-before-fields rule sees them as types)."""
    names = {}
    try:
        names = {
            v.number: v.name
            for v in scip_pb2.SymbolInformation.DESCRIPTOR.enum_types_by_name["Kind"].values
        }
    except (AttributeError, KeyError):
        return
    for doc in _stream_documents(data, scip_pb2):
        for si in doc.symbols:
            if not si.symbol.startswith(GO_SCHEME + " ") or si.symbol in ctx.def_kinds:
                continue
            mapped = _GO_SCIP_KINDS.get(names.get(int(getattr(si, "kind", 0)), ""), "")
            if mapped:
                ctx.def_kinds[si.symbol] = mapped


def _go_definition_modules(data: bytes, scip_pb2) -> set[str]:
    """The module paths the index DEFINES symbols for: what
    a checkout's go.mod files would say, read from the definitions when no
    checkout is at hand — one streaming pass."""
    out: set[str] = set()
    for doc in _stream_documents(data, scip_pb2):
        for occ in doc.occurrences:
            if occ.symbol_roles & 0x1 and occ.symbol.startswith(GO_SCHEME + " gomod "):
                parts = occ.symbol.split(" ", 4)
                if len(parts) >= 3:
                    out.add(parts[2])
    return out


def _parse_symbol(symbol: str) -> tuple[str, str, str] | None:
    """(qualified_name, kind, signature_hint) or None for skip-worthy
    symbols (namespaces, file pseudo-symbols, locals)."""
    if symbol.startswith("local "):
        return None
    if symbol.startswith(TS_SCHEME + " "):
        return _parse_ts_symbol(symbol)
    parts = symbol.split(" ", 4)
    if len(parts) < 5:
        return None
    names: list[str] = []
    kind = ""
    sig = ""
    go_first = _GO is not None and parts[0] == GO_SCHEME and parts[1] == "gomod"
    for m in _DESC_RE.finditer(parts[4]):
        name = m.group("quoted") or m.group("plain")
        if go_first:
            # The package path becomes the fast tier's scope
            go_first = False
            scope = _GO.scope(parts[2], name) if _GO is not None else None
            if scope is not None:
                names.append(scope)
                continue
        if name.startswith("<file>"):
            # File scope: scip-clang prefixes internal-linkage (static /
            # anonymous-namespace) symbols with a `<file>/path` descriptor.
            # Dropping the whole symbol would erase every file-local helper
            # from the compiler tier. Keep it, scoped by path so two files'
            # `helper()` stay distinct symbol_ids; `symbols_by_name("helper")`
            # still finds it via the `::helper` suffix. A bare `<file>` alone
            # (the file pseudo-symbol itself) is still skipped.
            scope = name[len("<file>") :].strip("/")
            if not scope:
                return None
            names.append(scope)
            continue
        names.append(name)
        if m.group("hash") is not None:
            kind = "function"
            # the hex hash IS scip-clang's overload disambiguator — carry it
            # as the signature so overloads land under distinct symbol_ids
            sig = f"(scip:{m.group('hash')})" if m.group("hash") else "()"
        elif m.group("term") == "#":
            kind = "class"
        elif m.group("term") == "/":
            kind = "namespace"
    if not names or kind in ("", "namespace"):
        return None
    if len(names) == 1 and "/" in names[0]:
        return None  # only the file pseudo-symbol, nothing scoped under it
    if _GO is not None and parts[0] == GO_SCHEME:
        kind = _go_kind(symbol, parts[4], kind)
    return "::".join(names), kind, sig


def _go_kind(symbol: str, descriptor: str, parsed: str) -> str:
    """The indexer's kind when the prepass recorded one; else
    the descriptor's shape — a `.` term under a `#` type is a field (or an
    interface method spec, indistinguishable without the kind: `field` is the
    safer rank), a bare `#` type is a struct, `()` stays a function."""
    known = _GO.def_kinds.get(symbol, "") if _GO is not None else ""
    if known:
        return known
    if parsed == "function":
        return parsed
    tail = descriptor.rstrip()
    if tail.endswith(".") and "#" in tail:
        return "field"
    if tail.endswith("#"):
        return "struct"
    return parsed


def _line_of(rng) -> int:
    return int(rng[0]) + 1 if rng else 0


_INHERIT_KINDS = frozenset({"class", "struct", "interface", "type", "enum"})  # incl. struct


def _implementation_targets(data: bytes, scip_pb2) -> dict[str, set[str]]:
    """symbol -> the symbols it `is_implementation`-relates to, over the whole
    index (one streaming pass): what `_direct_targets` needs to tell a
    declared base from an ancestor the emitter listed transitively."""
    out: dict[str, set[str]] = {}
    for doc in _stream_documents(data, scip_pb2):
        for si in doc.symbols:
            targets = {
                rel.symbol
                for rel in (getattr(si, "relationships", None) or [])
                if getattr(rel, "is_implementation", False)
            }
            if targets:
                out.setdefault(si.symbol, set()).update(targets)
    return out


def _direct_targets(targets: set[str], ancestors: dict[str, set[str]]) -> set[str]:
    """A extends B only where A explicitly
    derives from B. scip-typescript's `relationships()` lists EVERY ancestor
    of a class (and every ancestor member of a method), so a grandchild
    carried an `inherits` edge to each grandparent (langfuse:
    EventsQueryBuilder -> BaseEventsQueryBuilder, AbstractCTEQueryBuilder,
    AbstractQueryBuilder). A target another target already reaches is
    implied, not declared; the walk re-derives it at depth 2. A cycle keeps
    everything rather than nothing."""
    direct = {t for t in targets if not any(t in ancestors.get(u, ()) for u in targets if u != t)}
    return direct or targets


def _relationship_edges(
    doc_symbols,
    def_lines: dict[str, int],
    ancestors: dict[str, set[str]] | None = None,
) -> list[dict]:
    """`overrides` / `inherits` edges from SCIP relationships.

    scip-clang records `is_implementation` on a SymbolInformation for both
    a method overriding a base virtual and a class deriving from a base.
    Without these, an override's callers look empty (call sites bind to the
    base declaration) and the tree-sitter `inherits` edges miss every
    `class X final : public IBase` form. Method→method is `overrides`,
    type→type is `inherits`; mixed or unparseable pairs are skipped. The
    edge sits on the implementer's definition line in this document."""
    edges: list[dict] = []
    for si in doc_symbols:
        rels = getattr(si, "relationships", None) or []
        if not rels:
            continue
        src = _parse_symbol(si.symbol)
        if src is None:
            continue
        sq, skind, ssig = src
        line = def_lines.get(si.symbol, 0)
        targets = {rel.symbol for rel in rels if getattr(rel, "is_implementation", False)}
        if ancestors is not None:
            targets = _direct_targets(targets, ancestors)
        for rel in rels:
            if not getattr(rel, "is_implementation", False) or rel.symbol not in targets:
                continue
            dst = _parse_symbol(rel.symbol)
            if dst is None:
                continue
            tq, tkind, tsig = dst
            if skind == "function" and tkind == "function":
                kind = "overrides"
            elif skind in _INHERIT_KINDS and tkind in _INHERIT_KINDS:
                # class → class, and (TypeScript) implements / extends of interfaces
                kind = "inherits"
            else:
                continue
            if (tq, tsig) == (sq, ssig):
                continue
            edges.append(
                {
                    "edge_kind": kind,
                    "from_qualified_name": sq,
                    "from_signature": ssig,
                    "to_qualified_name": tq,
                    "to_signature": tsig,
                    "line": line,
                }
            )
    return edges


def _span_of(rng) -> tuple[int, int]:
    """(start_line, end_line), 1-based, from a SCIP range/enclosing_range
    ([startLine, startChar, endLine, endChar] or the 3-element short form
    [startLine, startChar, endChar] for single-line ranges)."""
    if not rng:
        return (0, 0)
    start = int(rng[0]) + 1
    end = int(rng[2]) + 1 if len(rng) >= 4 else start
    return (start, max(start, end))


# Factory templates whose FIRST template argument is the type they construct.
# The constructor call happens inside the library template's
# body, so the caller's TU carries only a type reference at the template
# argument — `saveTagTypeLoc` on the name token — and no CXXConstructExpr
# (scip-clang 0.4.0, verified on a fixture: `Widget w(4)`, `Widget(5)`,
# `Widget{6}`, `new Widget(7)` and a member-init list each emit a reference
# to the constructor symbol; `std::make_shared<Widget>(8)` emits
# `std/make_shared(hash).` plus `DB/Widget#`). The regex runs over the source
# text that precedes the type token on its line: a qualifier prefix
# (`make_shared<DB::Widget>`) and cv-qualifiers are allowed between the
# factory's `<` and the token.
_CTOR_FACTORY_NAMES = (
    "make_shared",
    "make_unique",
    "make_shared_for_overwrite",
    "make_unique_for_overwrite",
    "allocate_shared",
    "allocate_unique",
    "construct_at",
    "make_intrusive",
    "make_optional",
    "make_any",
    "in_place_type",
    "emplace",
)
_CTOR_FACTORY_RE = re.compile(
    r"\b(?:" + "|".join(_CTOR_FACTORY_NAMES) + r")\s*<\s*(?:(?:const|volatile|typename)\s+)*"
    r"(?:[A-Za-z_]\w*\s*::\s*)*$"
)
# The same rule from the factory's own occurrence to the type token, across
# line breaks: `std::make_shared<\n    Widget>(...)` puts the
# type on the line after the factory, where the single-line test above sees
# only indentation. The factory's occurrence (`std/make_shared(hash).`, a
# function reference) ends where the template argument list begins.
_CTOR_FACTORY_SPAN_RE = re.compile(
    r"^\s*<\s*(?:(?:const|volatile|typename)\s+)*(?:[A-Za-z_]\w*\s*::\s*)*$"
)
_FACTORY_SPAN_MAX_LINES = 8

CTOR_CALLS_FEATURE = "ctor_calls"
CXX_SCHEME = "cxx"  # scip-clang's symbol scheme


def _is_ctor_qname(qname: str) -> bool:
    parts = qname.split("::")
    return len(parts) >= 2 and bool(parts[-1]) and parts[-1] == parts[-2]


def _ctor_overloads(records, scip_pb2) -> dict[str, list[str]]:
    """class qualified name -> sorted constructor signature hints, from every
    occurrence of a constructor symbol in the index (declarations in a class
    body are reference-role occurrences, so a class whose header is included
    by any indexed TU contributes its overloads even when its .cpp is not in
    this delta). The hash IS scip-clang's overload identity, so each entry is
    one symbol_id on the server."""
    out: dict[str, set[str]] = {}
    for field, payload in records:
        if field != 2:
            continue
        doc = scip_pb2.Document()
        doc.ParseFromString(payload)
        for occ in doc.occurrences:
            parsed = _parse_symbol(occ.symbol)
            if parsed is None or parsed[1] != "function" or not _is_ctor_qname(parsed[0]):
                continue
            out.setdefault(parsed[0].rsplit("::", 1)[0], set()).add(parsed[2])
    return {k: sorted(v) for k, v in out.items()}


class _SourceLines:
    """Lines of the checkout's files, read on demand — the factory test needs
    the text before the type token on its line. `None` for a file the root
    does not hold (the converter then emits what it emitted before)."""

    def __init__(self, root: Path | None) -> None:
        self.root = root
        self._cache: dict[str, list[str] | None] = {}

    @property
    def available(self) -> bool:
        return self.root is not None and self.root.is_dir()

    def lines(self, rel: str) -> list[str] | None:
        if not self.available:
            return None
        if rel not in self._cache:
            if len(self._cache) > 64:
                self._cache.clear()
            try:
                assert self.root is not None
                self._cache[rel] = (
                    (self.root / rel).read_text("utf-8", errors="replace").splitlines()
                )
            except OSError:
                self._cache[rel] = None
        return self._cache[rel]


def _factory_type_ref(lines: list[str] | None, rng) -> bool:
    """Is the type token at SCIP range `rng` the first template argument of a
    constructing factory (`std::make_shared<` … `>`)? False without source."""
    if lines is None or not rng or len(rng) < 2:
        return False
    ln, col = int(rng[0]), int(rng[1])
    if ln < 0 or ln >= len(lines):
        return False
    return _CTOR_FACTORY_RE.search(lines[ln][:col]) is not None


def _factory_type_ref_span(
    lines: list[str] | None,
    rng,
    factory_ends: list[tuple[int, int]],
) -> int | None:
    """The 0-based line of the constructing factory whose template argument
    list the type token at `rng` opens, when the two are on DIFFERENT lines:
    the source between the factory occurrence's end and the
    token is `<`, cv-qualifiers and qualifier segments only. None otherwise,
    and always None without source. `factory_ends` are the (line, end_col)
    of the document's factory occurrences, sorted."""
    if lines is None or not rng or len(rng) < 2 or not factory_ends:
        return None
    ln, col = int(rng[0]), int(rng[1])
    if ln < 0 or ln >= len(lines):
        return None
    best: tuple[int, int] | None = None
    for f_ln, f_col in factory_ends:
        if f_ln >= ln:
            break
        if ln - f_ln <= _FACTORY_SPAN_MAX_LINES:
            best = (f_ln, f_col)
    if best is None:
        return None
    f_ln, f_col = best
    between = "\n".join([lines[f_ln][f_col:], *lines[f_ln + 1 : ln], lines[ln][:col]])
    return f_ln if _CTOR_FACTORY_SPAN_RE.search(between) is not None else None


def _top_level_records(data: bytes):
    """Yield (field, payload) for every length-delimited top-level record of
    an Index message (1 = metadata, 2 = documents, 3 = external_symbols)."""
    pos, end = 0, len(data)

    def varint(p: int) -> tuple[int, int]:
        shift = result = 0
        while True:
            b = data[p]
            result |= (b & 0x7F) << shift
            p += 1
            if not b & 0x80:
                return result, p
            shift += 7

    while pos < end:
        tag, pos = varint(pos)
        field, wire = tag >> 3, tag & 7
        if wire == 2:  # length-delimited
            length, pos = varint(pos)
            payload = data[pos : pos + length]
            pos += length
            yield field, payload
        elif wire == 0:
            _, pos = varint(pos)
        elif wire == 5:
            pos += 4
        elif wire == 1:
            pos += 8
        else:
            raise ValueError(f"unexpected wire type {wire} at {pos}")


def _document_path(payload) -> str:
    """A serialized Document's relative_path (field 1), read without parsing
    its occurrences."""
    for field, value in _top_level_records(payload):
        if field == 1:
            return bytes(value).decode("utf-8", "replace")
    return ""


def _stream_documents(data, scip_pb2, *, paths: set[str] | None = None, ordered: bool = False):
    """Yield scip.Document messages by streaming the Index's top-level
    records (field 2 = documents) instead of parsing one giant message —
    a full ClickHouse index is ~1GB, which trips python-protobuf's
    whole-message limits ("Wire format was corrupt"). `paths` parses only
    the documents with those relative paths; `ordered` yields them sorted by
    path (index order among equal paths), so the delta does not depend on
    the order a parallel indexer wrote its documents in."""
    records = (payload for field, payload in _top_level_records(data) if field == 2)
    if paths is not None or ordered:
        keyed = [(_document_path(payload), payload) for payload in records]
        if paths is not None:
            keyed = [kp for kp in keyed if kp[0] in paths]
        if ordered:
            keyed.sort(key=lambda kp: kp[0])
        records = (payload for _path, payload in keyed)
    for payload in records:
        doc = scip_pb2.Document()
        doc.ParseFromString(payload)
        yield doc


_TS_TYPE_KINDS = frozenset({"class", "interface", "type", "enum"})


def _index_scheme(data: bytes, scip_pb2) -> str:
    """The scheme of the first non-local symbol in the index (`cxx` for
    scip-clang, `scip-python`, `scip-typescript`, `scip-go`)."""
    for doc in _stream_documents(data, scip_pb2):
        for si in doc.symbols:
            if not si.symbol.startswith("local "):
                return si.symbol.split(" ", 1)[0]
        for occ in doc.occurrences:
            if not occ.symbol.startswith("local "):
                return occ.symbol.split(" ", 1)[0]
    return ""


def _project_root(data: bytes, scip_pb2) -> Path | None:
    """The checkout the index was produced from (Index.metadata.project_root,
    a file:// URI), or None when the metadata record is absent."""
    for field, payload in _top_level_records(data):
        if field == 1:
            md = scip_pb2.Metadata()
            md.ParseFromString(payload)
            root = str(md.project_root or "")
            if root.startswith("file://"):
                root = root[len("file://") :]
            return Path(root) if root else None
        if field == 2:
            break  # metadata precedes documents; do not scan the whole index
    return None


# The parser tier's generated-file rule, harness-side: Go's generated-file header
# before the package clause (golang.org/s/generatedcode) and the `@generated`
# marker other generators write in a leading comment.
_GO_GENERATED_RE = re.compile(r"^// Code generated .* DO NOT EDIT\.?[ \t]*$", re.M)
_GENERATED_MARK_RE = re.compile(r"^[ \t]*(?://|#|/\*+|\*|<!--|--|;)[ \t]*@generated\b", re.M)


def _is_generated(rel: str, lines: list[str] | None) -> bool:
    """A document whose source says it is generated (the index's own
    project root is the source); False when the source is unreadable."""
    if not lines:
        return False
    head = lines[:80]
    if rel.endswith(".go"):
        pre = []
        for ln in head:
            if ln.startswith("package "):
                break
            pre.append(ln)
        if _GO_GENERATED_RE.search("\n".join(pre)):
            return True
    return bool(_GENERATED_MARK_RE.search("\n".join(head[:8])))


def _read_index(index_path: str):
    """The index bytes, memory-mapped: the prepasses and the emit each walk
    the whole file, and a mapping keeps it in the page cache instead of the
    heap (an empty file maps nothing, so it reads as b"")."""
    with open(index_path, "rb") as fh:
        if os.fstat(fh.fileno()).st_size == 0:
            return b""
        return memoryview(mmap.mmap(fh.fileno(), 0, access=mmap.ACCESS_READ))


class _Run:
    """What converting one document reads from the whole index, and the
    counters the delta's stats report."""

    def __init__(
        self,
        src: _SourceLines,
        is_ts: bool,
        is_cxx: bool,
        ctors: dict[str, list[str]],
        ancestors: dict[str, set[str]],
        exclude_generated: bool,
    ) -> None:
        self.src = src
        self.is_ts = is_ts
        self.is_cxx = is_cxx
        self.ctors = ctors
        self.ancestors = ancestors
        self.exclude_generated = exclude_generated
        self.factory_edges = 0
        self.skipped_generated = 0


def _prepare(
    data, scip_pb2, source_root: str | None, exclude_generated: bool, path_prefix: str
) -> _Run:
    """The index-wide passes before the emit: the source root, the scheme's
    context (Go package scopes, TypeScript workspace map and definition
    kinds), the constructor overloads, the implementation ancestors."""
    if source_root is None:
        src = _SourceLines(_project_root(data, scip_pb2))
    else:
        src = _SourceLines(Path(source_root) if source_root else None)
    global _TS, _GO
    _TS = None
    scheme = _index_scheme(data, scip_pb2)
    is_ts = scheme == TS_SCHEME
    # Go symbols take the fast tier's package scope
    _GO = (
        _GoContext(src.root if src.available else None, path_prefix)
        if scheme == GO_SCHEME
        else None
    )
    if _GO is not None and not _GO.modules:
        _GO.modules = _go_definition_modules(data, scip_pb2)
    if _GO is not None:
        _go_prepass(data, scip_pb2, _GO)
    if is_ts:
        # The workspace map and the definition kinds before
        # any symbol is parsed (a term's kind is its definition's shape)
        _TS = _TsContext(ts_package_dirs(src.root if src.available else None), src)
        _ts_prepass(data, scip_pb2, _TS)
    ctors: dict[str, list[str]] = {}
    # constructor calls through factories are a C++ form (`std::make_shared<T>`)
    is_cxx = scheme == CXX_SCHEME
    if src.available and is_cxx:
        ctors = _ctor_overloads(_top_level_records(data), scip_pb2)
    ancestors = _implementation_targets(data, scip_pb2)
    return _Run(src, is_ts, is_cxx, ctors, ancestors, exclude_generated)


def _edge(kind: str, encl: tuple[str, str], to_q: str, to_sig: str, line: int) -> dict:
    return {
        "edge_kind": kind,
        "from_qualified_name": encl[0],
        "from_signature": encl[1],
        "to_qualified_name": to_q,
        "to_signature": to_sig,
        "line": line,
    }


def _factory_ends(doc, lines: list[str] | None, ctors: dict[str, list[str]]) -> list:
    """(0-based line, end col) of every factory call in the document, sorted,
    for a type argument that sits on a later line than its factory."""
    out: list[tuple[int, int]] = []
    if lines is None or not ctors:
        return out
    for occ in doc.occurrences:
        parsed = _parse_symbol(occ.symbol)
        if (
            parsed is not None
            and parsed[1] == "function"
            and not occ.symbol_roles & 0x1
            and len(occ.range) >= 3
            and parsed[0].rsplit("::", 1)[-1] in _CTOR_FACTORY_NAMES
        ):
            out.append((int(occ.range[0]), int(occ.range[-1])))
    return sorted(out)


def _convert_document(doc, run: _Run) -> dict | None:
    """One document's file entry: its definitions, and the edges from them;
    None for a document the delta leaves out."""
    rel = doc.relative_path
    is_ts, ctors = run.is_ts, run.ctors
    if is_ts and (rel.startswith("node_modules/") or "/node_modules/" in rel):
        return None  # a dependency's declaration file is not the repository
    lines = run.src.lines(rel)
    if run.exclude_generated and _is_generated(rel, lines):
        run.skipped_generated += 1  # the stub's source is in the index
        return None
    docs_by_symbol = {
        si.symbol: "\n".join(si.documentation)[:2000] for si in doc.symbols if si.documentation
    }
    symbols = []
    # Call attribution, two data regimes:
    #  - scip-python (and other modern emitters) attach enclosing_range
    #    to definitions -> attribute a reference to the INNERMOST
    #    containing definition span (exact).
    #  - scip-clang 0.4.0 emits no enclosing_range -> fall back to
    #    nearest-preceding-definition (correct for sequential C++ TUs,
    #    noise only for globals between function bodies). Spans win when
    #    present: the fallback misattributes calls between nested defs.
    fn_defs: list[tuple[int, str, str]] = []  # (line, qname, sig)
    fn_spans: list[tuple[int, int, str, str]] = []  # (start, end, qname, sig)
    refs: list[tuple[int, str]] = []
    type_refs: list[tuple[int, str]] = []  # TypeScript only
    factory_refs: list[tuple[int, str]] = []  # (line, class qname) under a factory
    seen_defs: set[str] = set()
    factory_ends = _factory_ends(doc, lines, ctors)
    for occ in doc.occurrences:
        parsed = _parse_symbol(occ.symbol)
        if parsed is None:
            continue
        qname, kind, sig = parsed
        line = _line_of(occ.range)
        if (
            kind == "class"
            and not occ.symbol_roles & 0x1
            and occ.symbol.rstrip().endswith("#")
            and qname in ctors
        ):
            if _factory_type_ref(lines, occ.range):
                # `std::make_shared<T>(...)`: the type token is the only trace
                # of the construction in this TU — a call to T's constructor
                factory_refs.append((line, qname))
            else:
                # the type on the line after `make_shared<`: the edge sits on
                # the factory's line, where the call begins
                f_ln = _factory_type_ref_span(lines, occ.range, factory_ends)
                if f_ln is not None:
                    factory_refs.append((f_ln + 1, qname))
        if occ.symbol_roles & 0x1:  # SymbolRole.Definition
            if occ.symbol in seen_defs:
                continue
            seen_defs.add(occ.symbol)
            span = _span_of(occ.enclosing_range)
            if is_ts and not span[0] and kind == "function" and lines is not None:
                # scip-typescript attaches no enclosing
                # range to `const X = forwardRef((…) => …)`; the
                # formatter's statement span stands in, so the
                # references inside the component attribute to it
                span = _ts_statement_span(lines, line)
            symbols.append(
                {
                    "qualified_name": qname,
                    "name": qname.split("::")[-1],
                    "kind": kind,
                    "signature": sig,
                    "line_start": line,
                    "line_end": span[1] if span[1] >= line else line,
                    "doc": docs_by_symbol.get(occ.symbol, ""),
                    "scip_symbol": occ.symbol,
                }
            )
            if kind == "function":
                fn_defs.append((line, qname, sig))
                if span[0]:
                    fn_spans.append((span[0], span[1], qname, sig))
        elif kind == "function" and is_ts and _ts_typeof_ref(lines, occ.range):
            # `ComponentProps<typeof Button>` names the
            # value in a TYPE position — a uses_type, not a call
            type_refs.append((line, occ.symbol))
        elif kind == "function":
            # only function-shaped refs become call edges; type refs
            # (Widget#) and namespace refs are not calls
            refs.append((line, occ.symbol))
        elif is_ts and kind in _TS_TYPE_KINDS and not occ.symbol_roles & 0x2:
            # A TypeScript type reference from inside a
            # unit is a `uses_type` edge (the compiler resolved it)
            type_refs.append((line, occ.symbol))

    fn_defs.sort()
    # innermost-first when spans exist: sort widest-first per start so a
    # later (narrower) containing span overwrites a wider one
    fn_spans.sort(key=lambda t: (t[0], -t[1]))

    def _enclosing(line: int) -> tuple[str, str] | None:
        encl = None
        for s_start, s_end, dq, dsig in fn_spans:
            if s_start <= line <= s_end:
                encl = (dq, dsig)  # innermost wins
            elif s_start > line:
                break
        if encl is None and not is_ts:
            # the nearest-preceding fallback is scip-clang's regime
            # (no enclosing_range); scip-typescript has spans, and an
            # import line between two functions must bind to neither
            for d_line, dq, dsig in fn_defs:
                if d_line <= line:
                    encl = (dq, dsig)
                else:
                    break
        return encl

    edges = []
    for edge_kind, pending in (("calls", refs), ("uses_type", type_refs)):
        for line, sym in pending:
            encl = _enclosing(line)
            target = _parse_symbol(sym)
            if encl is None or target is None:
                continue
            tq, _tkind, tsig = target
            # self-reference filter compares the OVERLOAD, not just the name:
            # render(double) calling render(int) is a real edge
            if (tq, tsig) != encl:
                edges.append(_edge(edge_kind, encl, tq, tsig, line))
    # Factory constructions: one `calls` edge per known constructor overload
    # of the type argument. The compiler resolved the TYPE exactly; which
    # overload the factory forwards to is not in the index (the hash carries
    # no arity), so a class with several constructors gets one edge per
    # overload at 0.8 — the parser tier's grade for a member resolved through
    # its class — and a single-constructor class keeps 1.0.
    for line, cls in factory_refs:
        encl = _enclosing(line)
        if encl is None:
            continue
        sigs = ctors.get(cls, [])
        ctor_name = f"{cls}::{cls.rsplit('::', 1)[-1]}"
        for tsig in sigs:
            if (ctor_name, tsig) == encl:
                continue
            edge = _edge("calls", encl, ctor_name, tsig, line)
            if len(sigs) > 1:
                edge["confidence"] = 0.8
            edges.append(edge)
            run.factory_edges += 1
    # the relationship edges (overrides / inherits) hang off the
    # implementer's definition line in this document
    def_lines: dict[str, int] = {}
    for occ in doc.occurrences:
        if occ.symbol_roles & 0x1 and occ.symbol not in def_lines:
            def_lines[occ.symbol] = _line_of(occ.range)
    edges.extend(_relationship_edges(doc.symbols, def_lines, run.ancestors))
    seen = set()
    uniq_edges = []
    for e in edges:
        # the target OVERLOAD is part of the identity: two constructors of
        # one class reached from one line are two edges
        k = (
            e["edge_kind"],
            e["from_qualified_name"],
            e["from_signature"],
            e["to_qualified_name"],
            e["to_signature"],
            e["line"],
        )
        if k not in seen:
            seen.add(k)
            uniq_edges.append(e)
    return {"path": rel, "deleted": False, "symbols": symbols, "edges": uniq_edges}


class DeltaStream:
    """A delta produced one file at a time: `head` (version, commit, base),
    `files` (a one-shot iterator, sorted by path), then `tail()` — the
    deleted paths, the stats and the features, complete once `files` is
    exhausted."""

    def __init__(
        self,
        index_path: str,
        changed: set[str] | None,
        deleted: list[str],
        commit: str,
        base: str,
        *,
        source_root: str | None = None,
        full: bool = False,
        exclude_generated: bool = False,
        path_prefix: str = "",
    ) -> None:
        scip_pb2 = _ensure_scip_pb2()
        data = _read_index(index_path)
        self._run = _prepare(data, scip_pb2, source_root, exclude_generated, path_prefix)
        self._deleted = sorted(set(deleted))
        self._prefix = path_prefix
        # A FULL index converted with its source claims the feature: the
        # server records that this namespace's compiler tier carries
        # constructor calls through factories, and code.callers stops
        # labelling a constructor's empty answer `ctor_edges_absent`. A
        # per-merge delta emits the edges for its files but cannot speak for
        # the namespace. Only scip-clang indexes carry the form; the other
        # tiers never compute factory edges, so they never claim them.
        self._claims_ctor_calls = (
            (changed is None or full) and self._run.src.available and self._run.is_cxx
        )
        self.head = {"delta_version": 1, "commit": commit, "base": base}
        self.files = self._files(data, scip_pb2, changed)

    def _files(self, data, scip_pb2, changed: set[str] | None):
        for doc in _stream_documents(data, scip_pb2, paths=changed, ordered=True):
            if changed is not None and doc.relative_path not in changed:
                continue
            entry = _convert_document(doc, self._run)
            if entry is None:
                continue
            if self._prefix:
                entry["path"] = f"{self._prefix}/{entry['path']}"
            yield entry

    def tail(self) -> dict:
        out: dict = {
            "deleted_files": self._deleted,
            "stats": {
                "factory_ctor_edges": self._run.factory_edges,
                "skipped_generated": self._run.skipped_generated,
            },
        }
        if self._claims_ctor_calls:
            out["features"] = [CTOR_CALLS_FEATURE]
        return out


def convert(
    index_path: str,
    changed: set[str] | None,
    deleted: list[str],
    commit: str,
    base: str,
    *,
    source_root: str | None = None,
    full: bool = False,
    exclude_generated: bool = False,
    path_prefix: str = "",
) -> dict:
    """The whole delta as one dict (the command line streams it instead).
    `changed`: the relative paths to emit (None = every document).
    `source_root`: the checkout to read source lines from for the factory
    constructor test. None = the index's own project_root;
    "" = disabled (the delta then carries no factory constructor edges and
    does not claim the feature). `full`: this delta covers the whole
    namespace (the harness's --full run lists every tracked file as
    changed, so `changed is None` alone cannot tell). `path_prefix`: the
    module's directory, prefixed onto every emitted path."""
    stream = DeltaStream(
        index_path,
        changed,
        deleted,
        commit,
        base,
        source_root=source_root,
        full=full,
        exclude_generated=exclude_generated,
        path_prefix=path_prefix,
    )
    files = list(stream.files)
    return {**stream.head, "files": files, **stream.tail()}


def write_delta(stream: DeltaStream, fh) -> dict:
    """Write the delta as compact JSON, one file entry per line, without
    holding more than one entry in memory. Returns the counts and the
    sha256 of the written text."""
    digest = hashlib.sha256()
    counts = {"files": 0, "symbols": 0, "edges": 0}

    def put(text: str) -> None:
        fh.write(text)
        digest.update(text.encode())

    compact = {"separators": (",", ":")}
    put(json.dumps(stream.head, **compact)[:-1] + ',"files":[')
    for i, entry in enumerate(stream.files):
        put(("\n" if i == 0 else ",\n") + json.dumps(entry, **compact))
        counts["files"] += 1
        counts["symbols"] += len(entry["symbols"])
        counts["edges"] += len(entry["edges"])
    tail = stream.tail()
    put("\n]," + json.dumps(tail, **compact)[1:] + "\n")
    return {
        **counts,
        **tail["stats"],
        "features": tail.get("features", []),
        "sha": digest.hexdigest(),
    }


def upload(
    payload,
    commit: str,
    base: str,
    loom_url: str,
    token: str,
    producer: str,
    *,
    org: str = "",
    namespace: str = "",
) -> int:
    """Upload the delta text read from `payload` (a file object at its start)
    in parts of at most _MAX_PART_BYTES, then wait for the apply."""
    import httpx

    parts = []
    while chunk := payload.read(_MAX_PART_BYTES):
        parts.append(chunk)
    parts = parts or [""]
    batch_id = uuid.uuid4().hex
    headers = {"Authorization": f"Bearer {token}"}
    with httpx.Client(base_url=loom_url, timeout=60.0, headers=headers) as client:
        for seq, part in enumerate(parts):
            r = client.post(
                "/v1/code.scip_ingest",
                json={
                    "batch_id": batch_id,
                    "seq": seq,
                    "total_parts": len(parts),
                    "commit_sha": commit,
                    "base_sha": base,
                    "producer": producer,
                    "payload": part,
                    "org": org,
                    "namespace": namespace,
                },
            )
            r.raise_for_status()
            print(f"  part {seq + 1}/{len(parts)} uploaded")
        print(f"batch {batch_id}: waiting for apply…")
        for _ in range(120):
            time.sleep(5)
            r = client.post(
                "/v1/code.scip_status",
                json={"batch_id": batch_id, "org": org, "namespace": namespace},
            )
            r.raise_for_status()
            status = r.json()
            if status["status"] == "applied":
                print("applied ✓")
                return 0
            if status["status"] == "failed":
                print(f"FAILED: {status.get('error')}", file=sys.stderr)
                return 1
        print("timed out waiting for apply (worker enabled?)", file=sys.stderr)
        return 1


def _strip_prefix(path: str, prefix: str) -> str:
    """A repository-relative changed path as the module-relative one the index
    knows; a path outside the module is left as is (it matches nothing)."""
    return path[len(prefix) + 1 :] if path.startswith(prefix + "/") else path


def _path_list(path: str | None) -> list[str]:
    if not path:
        return []
    return [ln.strip() for ln in Path(path).read_text().splitlines() if ln.strip()]


def _summary(counts: dict) -> str:
    return (
        f"delta: {counts['files']} files, {counts['symbols']} symbols, {counts['edges']} edges "
        f"({counts['factory_ctor_edges']} constructor calls through factories; "
        f"{counts['skipped_generated']} generated files dropped; "
        f"features {counts['features']})"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--index", required=True, help="path to index.scip")
    ap.add_argument("--commit", required=True)
    ap.add_argument("--base", default="")
    ap.add_argument("--changed-files", help="newline list; omit = full index")
    ap.add_argument("--deleted-files", help="newline list of deleted paths")
    ap.add_argument("--loom-url", default="")
    ap.add_argument("--token", default="")
    ap.add_argument("--producer", default="scip_harness")
    ap.add_argument("--org", default="", help="override loom org (multi-repo)")
    ap.add_argument("--namespace", default="", help="override loom namespace (multi-repo)")
    ap.add_argument("--dry-run", help="write delta JSON here instead of uploading")
    ap.add_argument(
        "--full",
        action="store_true",
        help="this delta is a full index of the namespace (claims producer features "
        "that speak for the whole namespace, e.g. ctor_calls)",
    )
    ap.add_argument(
        "--exclude-generated",
        action="store_true",
        help="drop documents whose source carries Go's `// Code generated … "
        "DO NOT EDIT.` header or a leading `@generated` marker — the entry that refuses "
        "them in the parser tier refuses them here too",
    )
    ap.add_argument(
        "--path-prefix",
        default="",
        help="repository directory the indexed module sits in (one "
        "scip-go run per module of a monorepo); prefixed onto every file path so "
        "the delta's paths are repository-relative like the parser tier's",
    )
    ap.add_argument(
        "--source-root",
        default=None,
        help="checkout to read source lines from for factory constructor calls; "
        "default: the index's project_root; '' disables",
    )
    args = ap.parse_args()
    if args.source_root and not Path(args.source_root).is_dir():
        # A root that names nothing maps no package directory: every TypeScript symbol
        # would be dropped and the delta would still look complete.
        sys.exit(f"--source-root {args.source_root!r} is not a directory")

    if not args.dry_run and not (args.loom_url and args.token):
        print("--loom-url and --token required to upload", file=sys.stderr)
        return 2

    prefix = args.path_prefix.strip("/")
    changed = None
    if args.changed_files:
        changed = {
            _strip_prefix(c, prefix) if prefix else c for c in _path_list(args.changed_files)
        }
    deleted = _path_list(args.deleted_files)
    if prefix:
        deleted = [f"{prefix}/{_strip_prefix(d, prefix)}" for d in deleted]
    stream = DeltaStream(
        args.index,
        changed,
        deleted,
        args.commit,
        args.base,
        source_root=args.source_root,
        full=args.full,
        exclude_generated=bool(args.exclude_generated),
        path_prefix=prefix,
    )

    if args.dry_run:
        # written beside the target and renamed into place: a reader never
        # sees a partial delta, and a failed run leaves no file
        out = Path(args.dry_run)
        tmp = out.with_name(f".{out.name}.partial")
        try:
            with tmp.open("w", encoding="utf-8") as fh:
                counts = write_delta(stream, fh)
            os.replace(tmp, out)
        finally:
            tmp.unlink(missing_ok=True)
        print(_summary(counts))
        print(f"wrote {args.dry_run} (sha {counts['sha'][:12]})")
        return 0
    with tempfile.TemporaryFile("w+", encoding="utf-8") as fh:
        counts = write_delta(stream, fh)
        print(_summary(counts))
        fh.seek(0)
        return upload(
            fh,
            args.commit,
            args.base,
            args.loom_url,
            args.token,
            args.producer,
            org=args.org,
            namespace=args.namespace,
        )


if __name__ == "__main__":
    raise SystemExit(main())
