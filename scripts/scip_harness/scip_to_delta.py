def _ensure_scip_pb2():
    """The vendored bindings (vendor/scip_pb2.py, generated by vendor/regenerate.sh)."""
    if str(_VENDOR) not in sys.path:
        sys.path.insert(0, str(_VENDOR))
    try:
        import scip_pb2
    except Exception as e:  # an ImportError, or protobuf's VersionError for an old runtime
        raise SystemExit(
            f"cannot load vendor/scip_pb2.py ({e}): the converter needs protobuf>=7.35.1"
        ) from e
    return scip_pb2


# scip-clang's symbol grammar: "cxx <manager> <pkg> <version> <descriptors>"
# (the scheme is `cxx`; CXX_SCHEME below).
# Descriptors chain namespaces (`Name/`), types (`Name#`), and functions
# (`name(hash).` — the hex hash disambiguates overloads). Verified against
# real scip-clang 0.4.0 output; see tests in the loom repo.
_DESC_RE = re.compile(
    r"(?:`(?P<quoted>[^`]+)`|(?P<plain>[^`/#().\s]+))"
    r"(?:\((?P<hash>[0-9a-f]*)\))?"
    r"(?P<term>[/#.])"
)


# --------------------------------------------------------------------------
# scip-typescript. Symbol grammar:
#   "scip-typescript npm <package> <version> <descriptors>"
# where the descriptors are the file path as namespace descriptors
# (`src/`, `server/`, …, the file name backtick-quoted: `scores.ts`/), then
# the item: `Name#` (class / interface / type alias / enum), `f().` (function
# or method), `x.` (term: a const, or a const-bound arrow function), `x0:`
# (meta: an object-type member — skipped), `(p)` (parameter — skipped),
# `[T]` (type parameter — skipped), `Class#`<constructor>`().`. The package
# name maps to a workspace directory through the checkout's package.json
# files, so a symbol's qualified name is the SAME module-scoped name the
# tree-sitter tier writes (`packages.shared.src.server.repositories.scores::
# getScoreById`), and reads merge the two tiers by qualified name.
# --------------------------------------------------------------------------
TS_SCHEME = "scip-typescript"
_TS_CODE_EXTS = (".ts", ".tsx", ".mts", ".cts", ".js", ".jsx", ".mjs", ".cjs", ".d.ts")
_TS_DESC_RE = re.compile(
    r"(?:`(?P<quoted>[^`]+)`|(?P<plain>[^`/#().:\[\]\s]+))"
    r"(?:\((?P<disamb>[^)]*)\)\.|(?P<term>[/#.:]))"
    r"|\((?P<param>[^)]*)\)|\[(?P<tparam>[^\]]*)\]"
)
_TS_TYPE_KEYWORDS = (
    ("interface ", "interface"),
    ("type ", "type"),
    ("enum ", "enum"),
    ("class ", "class"),
    ("abstract class ", "class"),
    ("namespace ", "module"),
    ("module ", "module"),
)


class _TsContext:
    """What the TypeScript branch of `_parse_symbol` needs beyond the symbol
    string: the workspace's package name → directory map, the kind of every
    definition (a term is a function when its definition has a body span),
    and the source lines to tell an interface from a class."""

    def __init__(self, pkg_dirs: dict[str, str], src: _SourceLines):
        self.pkg_dirs = pkg_dirs
        self.src = src
        self.def_kinds: dict[str, str] = {}


_TS: _TsContext | None = None


class _GoContext:
    """The Go compiler tier names a symbol the way the fast
    tier does (`lang_go.go_scope`): the repository directory dotted, then
    the package clause — `lib.proto.proto::Block::Rows`, `root.clickhouse::
    Open`. scip-go's own `<module>/<pkgpath>::Name` carries a `/`, which the
    name gate classes as native, so the compiler tier's Go
    rows would never bind for Go callers, and one definition under two
    qualified names would count as two candidates. The package clause is read from the
    first non-test `.go` file of the package directory in the checkout
    (`--source-root`, with `--path-prefix` for a module below the root);
    without a checkout, the path's last element (`/vN` folded) stands in."""

    def __init__(
        self,
        source_root: Path | None,
        path_prefix: str = "",
        modules: set[str] | None = None,
    ) -> None:
        self.root = source_root
        self.prefix = path_prefix.strip("/")
        self._clauses: dict[str, str] = {}
        # scip-go's own kind per definition symbol
        # (SymbolInformation.kind: Struct, Interface, Field, Method,
        # MethodSpecification, …) mapped to the fast tier's vocabulary
        self.def_kinds: dict[str, str] = {}
        # the repository's own module paths — from its go.mod files, else from
        # the index's definitions (`_go_prepass`); a symbol of any other module
        # (a dependency, the standard library) keeps scip-go's own name
        self.modules: set[str] = set(modules or ())
        if source_root is not None and not self.modules:
            base = source_root / self.prefix if self.prefix else source_root
            try:
                for gm in base.rglob("go.mod"):
                    m = re.search(r"(?m)^module\s+(\S+)", gm.read_text(errors="replace"))
                    if m:
                        self.modules.add(m.group(1))
            except OSError:
                pass

    @staticmethod
    def dir_scope(directory: str) -> str:
        d = directory.strip("/")
        return d.replace("/", ".") if d else "root"

    def clause(self, rel_dir: str, pkg_path: str) -> str:
        if rel_dir in self._clauses:
            return self._clauses[rel_dir]
        name = ""
        if self.root is not None:
            d = self.root / self.prefix / rel_dir if self.prefix else self.root / rel_dir
            try:
                # the clause of the package: a non-test file first, else a test
                # file of the package itself (`package x`), never `x_test`
                files = sorted(d.glob("*.go"))
                for f in [
                    *[f for f in files if not f.name.endswith("_test.go")],
                    *[f for f in files if f.name.endswith("_test.go")],
                ]:
                    m = _GO_PACKAGE_RE.search(f.read_text(errors="replace")[:4096])
                    if m and not m.group(1).endswith("_test"):
                        name = m.group(1)
                        break
            except OSError:
                name = ""
        if not name:
            segs = pkg_path.rstrip("/").split("/")
            last = segs[-1] if segs else ""
            if re.fullmatch(r"v\d+", last) and len(segs) > 1:
                last = segs[-2]
            name = last.replace("-", "_").replace(".", "_") or "main"
        self._clauses[rel_dir] = name
        return name

    def scope(self, module: str, pkg_path: str) -> str | None:
        """The fast tier's scope for an in-module package path; None for a
        package outside the module (a dependency, the standard library)."""
        if module not in self.modules and self.modules:
            return None
        external_test = pkg_path == module + "_test" or (
            pkg_path.endswith("_test") and pkg_path.startswith(module + "/")
        )
        if external_test:
            # Go's synthetic import path of an external test package
            # (`package cht_test` in `cht/`, `package clickhouse_test` at the
            # root): the directory is the real one, the clause the package's
            # clause plus `_test` — the fast tier's `cht.cht_test`
            rel = pkg_path[len(module) :].strip("/")[: -len("_test")].rstrip("/")
            directory = "/".join(p for p in (self.prefix, rel) if p)
            base_path = pkg_path[: -len("_test")]
            return f"{self.dir_scope(directory)}.{self.clause(rel, base_path)}_test"
        if not (pkg_path == module or pkg_path.startswith(module + "/")):
            return None
        rel = pkg_path[len(module) :].strip("/")
        directory = "/".join(p for p in (self.prefix, rel) if p)
        return f"{self.dir_scope(directory)}.{self.clause(rel, pkg_path)}"


_GO_PACKAGE_RE = re.compile(r"(?m)^package\s+([A-Za-z_]\w*)")
GO_SCHEME = "scip-go"
_GO: _GoContext | None = None


def ts_package_dirs(source_root: Path | None) -> dict[str, str]:
    """{package name: repo-relative dir} for the checkout's workspace packages
    (scip_ts_paths.workspace_packages); the root package maps to ''. A name
    two package.json files declare maps to the first in path order."""
    if source_root is None or not source_root.exists():
        return {}
    if str(_HERE) not in sys.path:
        sys.path.insert(0, str(_HERE))
    from scip_ts_paths import workspace_packages

    out: dict[str, str] = {}
    for name, pkg_dir, _data in workspace_packages(source_root):
        rel = pkg_dir.relative_to(source_root).as_posix()
        out.setdefault(name, "" if rel == "." else rel)
    return out


def _ts_module_scope(path: str) -> str:
    stem = path[: path.rfind(".")] if "." in path.rsplit("/", 1)[-1] else path
    if stem.endswith(".d"):
        stem = stem[:-2]
    return stem.replace("/", ".")


def _ts_descriptors(desc: str) -> list[tuple[str, str, str]]:
    """[(name, suffix, disambiguator)] with suffix one of `/ # . :` `()`
    (method), `param`, `tparam`."""
    out: list[tuple[str, str, str]] = []
    for m in _TS_DESC_RE.finditer(desc):
        if m.group("param") is not None:
            out.append((m.group("param"), "param", ""))
        elif m.group("tparam") is not None:
            out.append((m.group("tparam"), "tparam", ""))
        else:
            name = m.group("quoted") or m.group("plain") or ""
            if m.group("disamb") is not None:
                out.append((name, "()", m.group("disamb")))
            else:
                out.append((name, m.group("term") or "", ""))
    return out


def _parse_ts_symbol(symbol: str) -> tuple[str, str, str] | None:
    """(qualified_name, kind, signature) for a scip-typescript symbol of a
    workspace package; None for locals, externals, files, parameters, meta
    members and type parameters."""
    ctx = _TS
    if ctx is None or symbol.startswith("local "):
        return None
    parts = symbol.split(" ", 4)
    if len(parts) < 5 or parts[1] != "npm":
        return None
    pkg_dir = ctx.pkg_dirs.get(parts[2])
    if pkg_dir is None:
        return None  # an external package (zod, react, typescript's lib)
    descs = _ts_descriptors(parts[4])
    path_segs: list[str] = []
    items: list[tuple[str, str, str]] = []
    file_seen = False
    for name, suffix, disamb in descs:
        if not file_seen:
            if suffix == "/":
                path_segs.append(name)
                if name.endswith(_TS_CODE_EXTS):
                    file_seen = True
                continue
            return None  # an item before any file: not a shape we index
        if suffix in ("param", "tparam", ":"):
            return None  # parameters, type parameters, object-type members
        items.append((name, suffix, disamb))
    if not file_seen or not items:
        return None  # the file pseudo-symbol itself, or a namespace
    rel_path = "/".join(path_segs)
    full = f"{pkg_dir}/{rel_path}" if pkg_dir else rel_path
    names = ["constructor" if n == "<constructor>" else n for n, _s, _d in items]
    qname = "::".join((_ts_module_scope(full), *names))
    last_suffix = items[-1][1]
    if last_suffix == "()":
        kind, sig = "function", f"(scip:{items[-1][2]})" if items[-1][2] else "()"
    elif last_suffix == "#":
        kind, sig = ctx.def_kinds.get(symbol, "class"), ""
    elif last_suffix == ".":
        kind, sig = ctx.def_kinds.get(symbol, "const"), ""
    else:
        return None
    return qname, kind, sig


# A component declared through a higher-order wrapper
# (`forwardRef<P>(…)`, `memo(…)`) is a function unit in both tiers
_TS_HOC_RE = re.compile(r"\b(?:React\.)?(?:forwardRef|memo|observer|lazy)\s*[<(]")


_TS_CLOSE_RE = re.compile(r"^[\]\}\)]+;?\s*$")


_TS_TYPEOF_RE = re.compile(r"\btypeof\s+$")


def _ts_typeof_ref(lines: list[str] | None, rng) -> bool:
    """Is the occurrence the operand of a `typeof` type query? The text
    before the token on its line ends with `typeof `."""
    if lines is None or len(rng) < 2:
        return False
    row, col = int(rng[0]), int(rng[1])
    if row >= len(lines):
        return False
    return bool(_TS_TYPEOF_RE.search(lines[row][:col]))


def _ts_statement_span(lines: list[str], line: int) -> tuple[int, int]:
    """(start, end), 1-based, of the formatter-closed statement that starts
    at `line`: the run of lines down to the first column-0 closer (`)`,
    `});`, `};`), stopping before the next column-0 token. (0, 0) for a
    statement that ends on its own line or an unclosed one."""
    if line < 1 or line > len(lines) or lines[line - 1].rstrip().endswith(";"):
        return (0, 0)
    for i in range(line, len(lines)):
        text = lines[i]
        if _TS_CLOSE_RE.match(text):
            return (line, i + 1)
        if text[:1] not in ("", " ", "\t", "\n", "\r", "/") and text.strip():
            return (0, 0)  # another top-level token before any closer
    return (0, 0)


def _ts_def_kind(symbol: str, occ, lines: list[str] | None) -> str:
    """The kind a TypeScript definition occurrence has: a `#` symbol by the
    keyword on its line (`interface` / `type` / `enum` / `class`), a `().`
    method a function, a `.` term a function when it has a body span
    (a const-bound arrow / function expression) else a const."""
    desc = symbol.split(" ", 4)[-1]
    descs = _ts_descriptors(desc)
    suffix = descs[-1][1] if descs else ""
    if suffix == "()":
        return "function"
    line_text = ""
    if lines is not None and len(occ.range) >= 3 and 0 <= int(occ.range[0]) < len(lines):
        line_text = lines[int(occ.range[0])].lstrip()
        for prefix in ("export default ", "export ", "declare "):
            if line_text.startswith(prefix):
                line_text = line_text[len(prefix) :]
    if suffix == "#":
        for kw, kind in _TS_TYPE_KEYWORDS:
            if line_text.startswith(kw):
                return kind
        return "class"
    if suffix == ".":
        span = _span_of(occ.enclosing_range)
        if span[0] or "=>" in line_text or "function" in line_text or _TS_HOC_RE.search(line_text):
            return "function"
        # A term under a type (`StringFilter#field.`) is a
        # class property, not a module const
        return "field" if len(descs) >= 2 and descs[-2][1] == "#" else "const"
    return ""


def _ts_prepass(data: bytes, scip_pb2, ctx: _TsContext) -> None:
    """Every definition's kind, index-wide, so a reference to a term in
    another document knows whether its target is a function (a `calls`
    edge) or a type (`uses_type`) — one streaming pass before the emit."""
    for doc in _stream_documents(data, scip_pb2):
        if doc.relative_path.startswith("node_modules/") or "/node_modules/" in doc.relative_path:
            continue
        lines = ctx.src.lines(doc.relative_path)
        for occ in doc.occurrences:
            if not occ.symbol_roles & 0x1 or occ.symbol.startswith("local "):
                continue
            if occ.symbol in ctx.def_kinds:
                continue
            kind = _ts_def_kind(occ.symbol, occ, lines)
            if kind:
                ctx.def_kinds[occ.symbol] = kind


