#!/usr/bin/env python3
"""Convert a scip-clang index into loom's SCIP JSON delta and upload it.

Producer-side normalization: loom's server never parses protobuf — this
script does:

    index.scip (protobuf)
      -> per-file symbols (definition occurrences) + call/type edges
         (reference occurrences located inside a definition's range)
      -> versioned JSON delta (server/code/app/index/scip_delta.py)
      -> chunked POST to /v1/code.scip_ingest (<=8MB parts)
      -> poll /v1/code.scip_status until applied

Deps (NOT server deps): `pip install 'protobuf>=7.35.1' httpx` — the protobuf
runtime for the vendored bindings (vendor/scip_pb2.py), httpx for upload mode.

Usage:
    scip_to_delta.py --index index.scip --commit <sha> [--base <sha>]
        [--changed-files files.txt] [--deleted-files deleted.txt]
        [--full] [--source-root <checkout>]
        --loom-url https://loom.example --token $LOOM_API_KEY
        [--dry-run out.json]

Constructor calls: scip-clang records a reference to the
constructor for every direct construction (`T x(...)`, `T(...)`, `T{...}`,
`new T(...)`, member-init lists) but not for a construction inside a
library template (`std::make_shared<T>(...)`): there the caller's TU holds
only a TYPE reference at the template argument. The converter reads the
source line under that reference (from `--source-root`, default the index's
project_root) and emits a `calls` edge to every known constructor overload
of T — 1.0 for a single constructor, 0.8 each for several. A `--full`
conversion with source claims the `ctor_calls` feature, which the server
records per namespace so the read side stops labelling a constructor's
empty answer `ctor_edges_absent`. The type argument may sit on the line
after the factory (`std::make_shared<\n    T>(...)`): the
test then runs from the factory occurrence's end to the token.
"""

